@router.post(
    "/sessions",
    response_model=SessionResponse,
    status_code=status.HTTP_201_CREATED,
    summary="Create Security Session",
    description="Create a new security session with specified tools activated"
)
async def create_security_session(
    request: CreateSessionRequest,
    security_service: SecurityToolsService = Depends(get_security_service),
    security_profile: SecurityProfile = Depends(
        get_current_user_security_profile
    )
) -> SessionResponse:
    """Create new security session."""
    start_time = datetime.now()

    try:
        # Update security profile with request parameters
        security_profile.operation_mode = request.operation_mode
        security_profile.session_timeout_minutes = (
            request.session_timeout_minutes
        )

        # Create session
        session = await security_service.create_security_session(
            user_id=security_profile.user_id,
            security_profile=security_profile,
            tools_requested=request.tools_requested
        )

        # Calculate processing time
        processing_time = (datetime.now() - start_time).total_seconds() * 1000

        return SessionResponse(
            success=True,
            timestamp=datetime.now().isoformat(),
            processing_time_ms=processing_time,
            constitutional_compliant=processing_time <= 1000,
            session_id=str(session.id),
            session_token=session.session_token,
            tools_activated=session.tools_in_use,
            expires_at=(
                session.expires_at.isoformat() if session.expires_at else None
            )
        )

    except Exception as e:
        logger.error(f"Failed to create security session: {e}")
        processing_time = (datetime.now() - start_time).total_seconds() * 1000

        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail={
                "error": str(e),
                "processing_time_ms": processing_time,
                "constitutional_compliant": processing_time <= 1000
            }
        )


@router.post(
    "/sessions/{session_id}/hunt",
    response_model=HuntResponse,
    summary="Execute Threat Hunt",
    description="Execute threat hunting across activated security tools"
)
async def execute_threat_hunt(
    session_id: str,
    request: ThreatHuntRequest,
    security_service: SecurityToolsService = Depends(get_security_service)
) -> HuntResponse:
    """Execute threat hunting operation."""
    start_time = datetime.now()

    try:
        # Get session
        session = security_service.active_sessions.get(UUID(session_id))
        if not session:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Security session not found"
            )

        # Prepare hunt configuration
        hunt_config = {
            'hunt_type': request.hunt_type,
            'indicators': request.indicators,
            'ai_enhance': request.ai_enhance
        }

        if request.tools_filter:
            hunt_config['tools_filter'] = request.tools_filter

        # Execute hunt
        hunt_results = await security_service.execute_threat_hunting(
            session=session,
            hunt_config=hunt_config
        )

        # Calculate processing time
        processing_time = (datetime.now() - start_time).total_seconds() * 1000

        return HuntResponse(
            success=True,
            timestamp=datetime.now().isoformat(),
            processing_time_ms=processing_time,
            constitutional_compliant=processing_time <= 1000,
            hunt_id=hunt_results.get('hunt_id'),
            results=hunt_results.get('results', {}),
            tools_used=hunt_results.get('tools_used', []),
            ai_enhancement=hunt_results.get('ai_enhancement', {})
        )

    except ValueError as e:
        logger.error(f"Invalid hunt request: {e}")
        processing_time = (datetime.now() - start_time).total_seconds() * 1000

        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={
                "error": str(e),
                "processing_time_ms": processing_time,
                "constitutional_compliant": processing_time <= 1000
            }
        )

    except Exception as e:
        logger.error(f"Threat hunt failed: {e}")
        processing_time = (datetime.now() - start_time).total_seconds() * 1000

        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail={
                "error": str(e),
                "processing_time_ms": processing_time,
                "constitutional_compliant": processing_time <= 1000
            }
        )


