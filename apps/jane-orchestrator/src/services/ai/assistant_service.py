    async def _analyze_user_context(
        self,
        user_id: str,
        current_context: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Analyze user's current context for suggestions."""
        analysis = {
            'active_tools': current_context.get('active_tools', []),
            'current_tasks': current_context.get('current_tasks', []),
            'recent_actions': current_context.get('recent_actions', []),
            'time_of_day': datetime.now().hour,
            'workload_level': 'medium',
            'context_switches': current_context.get('context_switches', 0)
        }

        # Assess workload level
        task_count = len(analysis['current_tasks'])
        if task_count > 10:
            analysis['workload_level'] = 'high'
        elif task_count < 3:
            analysis['workload_level'] = 'low'

        return analysis

    async def _assess_focus_state(
        self,
        user_id: str,
        context_analysis: Dict[str, Any],
        user_profile: Optional[UserProfile]
    ) -> Dict[str, Any]:
        """Assess user's current focus state."""
        focus_state = {
            'level': 'medium',  # low, medium, high
            'stability': 'stable',  # stable, declining, improving
            'optimal_duration': 25,  # minutes
            'break_frequency': 5,  # minutes
            'distractions': []
        }

        # Analyze context switches
        switches = context_analysis.get('context_switches', 0)
        if switches > 5:
            focus_state['level'] = 'low'
            focus_state['stability'] = 'declining'
        elif switches < 2:
            focus_state['level'] = 'high'

        # Apply user accommodations
        if user_profile and user_profile.adhd_accommodations:
            adhd = user_profile.adhd_accommodations
            if adhd.get('short_focus_periods'):
                focus_state['optimal_duration'] = 15
                focus_state['break_frequency'] = 3

        return focus_state

    async def _generate_domain_suggestions(
        self,
        context_analysis: Dict[str, Any],
        focus_state: Dict[str, Any],
        user_profile: Optional[UserProfile]
    ) -> List[Dict[str, Any]]:
        """Generate domain-specific suggestions."""
        suggestions = []

        active_tools = context_analysis.get('active_tools', [])

        for tool in active_tools:
            # Find tool domain
            domain = self._get_tool_domain(tool)
            if domain:
                domain_info = self.domain_prompts.get(domain, {})

                suggestion = {
                    'type': 'tool_optimization',
                    'tool': tool,
                    'domain': domain.value,
                    'description': f"Optimize {tool} workflow in {domain_info.get('context', 'general')} context",
                    'priority': self._calculate_suggestion_priority(tool, focus_state),
                    'estimated_time': focus_state.get('optimal_duration', 25)
                }
                suggestions.append(suggestion)

        return suggestions

    def _apply_executive_accommodations(
        self,
        suggestions: List[Dict[str, Any]],
        user_profile: Optional[UserProfile]
    ) -> List[Dict[str, Any]]:
        """Apply executive function accommodations to suggestions."""
        if not user_profile:
            return suggestions

        accommodated_suggestions = []

        for suggestion in suggestions:
            # ADHD accommodations
            if user_profile.adhd_accommodations:
                adhd = user_profile.adhd_accommodations

                if adhd.get('break_tasks_down'):
                    suggestion['breakdown_available'] = True

                if adhd.get('time_awareness'):
                    suggestion['time_estimate'] = suggestion.get(
                        'estimated_time', 25)
                    suggestion['deadline_awareness'] = True

                if adhd.get('progress_indicators'):
                    suggestion['progress_tracking'] = True

            # Autism accommodations
            if user_profile.autism_accommodations:
                autism = user_profile.autism_accommodations

                if autism.get('detailed_descriptions'):
                    suggestion['detailed_steps'] = True

                if autism.get('predictable_patterns'):
                    suggestion['routine_compatible'] = True

            accommodated_suggestions.append(suggestion)

        return accommodated_suggestions

    def _create_breakdown_prompt(
        self,
        context: Dict[str, Any],
        domain: TaskDomain
    ) -> str:
        """Create prompt for AI task breakdown."""
        domain_info = self.domain_prompts.get(domain, {})

        prompt = f"""
        Break down the following task for a user with executive function needs:
        
        Task: {context['task_description']}
        Domain: {domain_info.get('context', 'general')}
        Complexity: {context['complexity']}
        Available Tools: {', '.join(context['domain_tools'])}
        
        User Accommodations:
        - ADHD support: {context['user_accommodations'].get('adhd_accommodations', {})}
        - Autism support: {context['user_accommodations'].get('autism_accommodations', {})}
        
        Provide a structured breakdown with:
        1. Clear, actionable steps (5-7 steps maximum)
        2. Time estimates for each step
        3. Required tools for each step
        4. Dependencies between steps
        5. Break points for focus management
        
        Format as JSON with steps array.
        """

        return prompt.strip()

