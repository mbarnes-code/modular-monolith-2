    def _optimize_for_executive_function(
        self,
        breakdown: Dict[str, Any],
        user_profile: Optional[UserProfile]
    ) -> Dict[str, Any]:
        """Optimize breakdown for executive function support."""
        if not user_profile:
            return breakdown

        steps = breakdown.get('steps', [])

        # Add break points for ADHD users
        if (user_profile.adhd_accommodations and
                user_profile.adhd_accommodations.get('frequent_breaks')):

            optimized_steps = []
            for i, step in enumerate(steps):
                optimized_steps.append(step)

                # Add break after each step for long tasks
                if step.get('estimated_minutes', 0) > 30:
                    optimized_steps.append({
                        'title': 'Take a Break',
                        'description': 'Short break to maintain focus',
                        'estimated_minutes': 5,
                        'is_break': True
                    })

            breakdown['steps'] = optimized_steps

        return breakdown

    def _get_tool_domain(self, tool_name: str) -> Optional[TaskDomain]:
        """Get domain for a tool name."""
        security_tools = ['MISP', 'HELK',
                          'SecurityOnion', 'YARA-X', 'CyberChef']
        productivity_tools = ['n8n', 'Dispatch', 'Mealie', 'Actual Budget']
        mtg_tools = ['Commander Spellbook', 'MTG Commander Map']
        infrastructure_tools = ['Kong', 'KasmVNC', 'Ghostwriter']

        if tool_name in security_tools:
            return TaskDomain.SECURITY
        elif tool_name in productivity_tools:
            return TaskDomain.PRODUCTIVITY
        elif tool_name in mtg_tools:
            return TaskDomain.MTG
        elif tool_name in infrastructure_tools:
            return TaskDomain.INFRASTRUCTURE

        return None

    def _calculate_suggestion_priority(
        self,
        tool: str,
        focus_state: Dict[str, Any]
    ) -> float:
        """Calculate suggestion priority based on context."""
        base_priority = 0.5

        # Adjust based on focus state
        focus_level = focus_state.get('level', 'medium')
        if focus_level == 'high':
            base_priority += 0.2
        elif focus_level == 'low':
            base_priority -= 0.2

        return max(0.1, min(1.0, base_priority))

    def _analyze_task_priorities(
        self,
        tasks: List[Task],
        time_available: Optional[int],
        energy_level: str
    ) -> Dict[str, Any]:
        """Analyze task priorities for next action suggestion."""
        analysis = {
            'urgent_tasks': [],
            'quick_wins': [],
            'focus_tasks': [],
            'energy_match': []
        }

        for task in tasks:
            # Check urgency
            if task.deadline and task.deadline <= datetime.now() + timedelta(hours=24):
                analysis['urgent_tasks'].append(task)

            # Check for quick wins
            if task.estimated_duration_minutes and task.estimated_duration_minutes <= 15:
                analysis['quick_wins'].append(task)

            # Check focus requirements
            if task.complexity in [TaskComplexity.COMPLEX.value, TaskComplexity.EXTENSIVE.value]:
                analysis['focus_tasks'].append(task)

            # Match energy level
            if energy_level == 'low' and task.complexity == TaskComplexity.SIMPLE.value:
                analysis['energy_match'].append(task)
            elif energy_level == 'high' and task.complexity == TaskComplexity.EXTENSIVE.value:
                analysis['energy_match'].append(task)

        return analysis

    def _assess_executive_factors(
        self,
        user_id: str,
        user_profile: Optional[UserProfile],
        current_tasks: List[Task]
    ) -> Dict[str, Any]:
        """Assess executive function factors."""
        factors = {
            'context_switching_cost': 1.0,
            'attention_span': 25,  # minutes
            'working_memory_load': 0.5,
            'decision_fatigue': 0.3
        }

        # Adjust based on user accommodations
        if user_profile and user_profile.adhd_accommodations:
            adhd = user_profile.adhd_accommodations

            if adhd.get('context_switching_difficulty'):
                factors['context_switching_cost'] = 1.5

            if adhd.get('short_attention_span'):
                factors['attention_span'] = 15

        # Adjust based on current workload
        task_count = len(current_tasks)
        if task_count > 5:
            factors['working_memory_load'] = min(
                1.0, factors['working_memory_load'] + 0.2)
            factors['decision_fatigue'] = min(
                1.0, factors['decision_fatigue'] + 0.3)

        return factors

    async def _generate_action_recommendation(
        self,
        task_analysis: Dict[str, Any],
        executive_factors: Dict[str, Any],
        user_profile: Optional[UserProfile]
    ) -> Dict[str, Any]:
        """Generate next action recommendation."""
        recommendations = []

        # Check for urgent tasks first
        if task_analysis['urgent_tasks']:
            task = task_analysis['urgent_tasks'][0]
            recommendations.append({
                'type': 'urgent_task',
                'task_id': task.id,
                'description': f"Complete urgent task: {task.title}",
                'reasoning': "This task has an approaching deadline",
                'benefit_score': 0.9
            })

        # Check for quick wins if attention is low
        if (executive_factors['attention_span'] < 20 and
                task_analysis['quick_wins']):
            task = task_analysis['quick_wins'][0]
            recommendations.append({
                'type': 'quick_win',
                'task_id': task.id,
                'description': f"Quick task: {task.title}",
                'reasoning': "Build momentum with a quick completion",
                'benefit_score': 0.7
            })

        # Suggest focus tasks if attention is high
        if (executive_factors['attention_span'] > 30 and
                task_analysis['focus_tasks']):
            task = task_analysis['focus_tasks'][0]
            recommendations.append({
                'type': 'focus_task',
                'task_id': task.id,
                'description': f"Deep work: {task.title}",
                'reasoning': "Good time for focused, complex work",
                'benefit_score': 0.8
            })

        # Default to energy-matched tasks
        if task_analysis['energy_match']:
            task = task_analysis['energy_match'][0]
            recommendations.append({
                'type': 'energy_matched',
                'task_id': task.id,
                'description': f"Energy-matched task: {task.title}",
                'reasoning': "Task complexity matches current energy level",
                'benefit_score': 0.6
            })

        # Return best recommendation
        if recommendations:
            return max(recommendations, key=lambda x: x['benefit_score'])
        else:
            return {
                'type': 'break',
                'description': 'Take a short break to recharge',
                'reasoning': 'No optimal tasks available right now',
                'benefit_score': 0.5
            }

    def _select_focus_pattern(
        self,
        duration_minutes: int,
        user_profile: Optional[UserProfile]
    ) -> Dict[str, Any]:
        """Select optimal focus pattern for work session."""
        # Default to pomodoro
        pattern = self.focus_patterns['pomodoro']

        # Adjust based on session length
        if duration_minutes >= 120:
            pattern = self.focus_patterns['flow_state']
        elif duration_minutes >= 90:
            pattern = self.focus_patterns['deep_work']
        elif duration_minutes <= 30:
            pattern = self.focus_patterns['micro_tasks']

        # Apply user accommodations
        if user_profile and user_profile.adhd_accommodations:
            adhd = user_profile.adhd_accommodations

            if adhd.get('short_focus_periods'):
                pattern = self.focus_patterns['micro_tasks']
            elif adhd.get('hyperfocus_tendency'):
                pattern = self.focus_patterns['flow_state']

        return pattern

    def _optimize_task_sequence(
        self,
        tasks: List[Task],
        focus_pattern: Dict[str, Any],
        user_profile: Optional[UserProfile]
    ) -> List[Dict[str, Any]]:
        """Optimize task sequence for focus pattern."""
        sequence = []

        # Sort tasks by priority and complexity
        sorted_tasks = sorted(tasks, key=lambda t: (
            t.priority == 'critical',
            t.complexity == 'extensive',
            t.deadline is not None
        ), reverse=True)

        focus_duration = focus_pattern['duration_minutes']

        for task in sorted_tasks:
            estimated_time = task.estimated_duration_minutes or 25

            if estimated_time <= focus_duration:
                sequence.append({
                    'task': task,
                    'duration': estimated_time,
                    'type': 'complete'
                })
            else:
                # Break large tasks into focus chunks
                chunks = (estimated_time + focus_duration -
                          1) // focus_duration
                for i in range(chunks):
                    sequence.append({
                        'task': task,
                        'duration': min(focus_duration, estimated_time - i * focus_duration),
                        'type': 'chunk',
                        'chunk_number': i + 1,
                        'total_chunks': chunks
                    })

        return sequence

    def _create_break_schedule(
        self,
        duration_minutes: int,
        focus_pattern: Dict[str, Any]
    ) -> List[Dict[str, Any]]:
        """Create break schedule for work session."""
        breaks = []
        focus_duration = focus_pattern['duration_minutes']
        break_duration = focus_pattern['break_minutes']

        current_time = 0
        while current_time + focus_duration < duration_minutes:
            current_time += focus_duration
            breaks.append({
                'time': current_time,
                'duration': break_duration,
                'type': 'regular_break'
            })
            current_time += break_duration

        return breaks

    def _get_focus_tips(
        self,
        user_profile: Optional[UserProfile],
        energy_level: str
    ) -> List[str]:
        """Get focus tips based on user profile and energy level."""
        tips = [
            "Minimize distractions in your environment",
            "Stay hydrated and maintain good posture",
            "Use a timer to track focus periods"
        ]

        if user_profile and user_profile.adhd_accommodations:
            adhd = user_profile.adhd_accommodations

            if adhd.get('fidgeting_helps'):
                tips.append("Keep a fidget toy or stress ball nearby")

            if adhd.get('background_noise_helpful'):
                tips.append("Try white noise or instrumental music")

            if adhd.get('visual_reminders'):
                tips.append("Use visual cues to stay on track")

        if energy_level == 'low':
            tips.extend([
                "Start with easier tasks to build momentum",
                "Consider a short walk or stretch break"
            ])
        elif energy_level == 'high':
            tips.extend([
                "Tackle your most challenging tasks first",
                "Take advantage of peak focus time"
            ])

        return tips

    def _get_session_focus_tips(
        self,
        user_profile: Optional[UserProfile]
    ) -> List[str]:
        """Get session-specific focus tips."""
        tips = [
            "Set a clear intention for this work session",
            "Prepare all needed materials before starting",
            "Turn off non-essential notifications"
        ]

        if user_profile:
            if user_profile.adhd_accommodations:
                tips.extend([
                    "Use body doubling (work alongside someone)",
                    "Set up rewards for completing focus blocks",
                    "Keep a notepad for capturing stray thoughts"
                ])

            if user_profile.autism_accommodations:
                tips.extend([
                    "Maintain consistent environmental conditions",
                    "Follow your established routine patterns",
                    "Use familiar tools and interfaces"
                ])

        return tips

    def _create_contingency_plans(
        self,
        tasks: List[Task]
    ) -> List[Dict[str, Any]]:
        """Create contingency plans for work session."""
        plans = [
            {
                'scenario': 'losing_focus',
                'action': 'Switch to a simpler task or take a break',
                'backup_tasks': [t for t in tasks if t.complexity == 'simple']
            },
            {
                'scenario': 'technical_issues',
                'action': 'Work on tasks that don\'t require problematic tools',
                'backup_tasks': [t for t in tasks if not t.primary_tool]
            },
            {
                'scenario': 'low_energy',
                'action': 'Focus on organizational or planning tasks',
                'backup_tasks': [t for t in tasks if 'plan' in (t.title or '').lower()]
            }
        ]

        return plans
