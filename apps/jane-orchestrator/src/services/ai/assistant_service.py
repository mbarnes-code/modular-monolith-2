    async def get_contextual_suggestions(
        self,
        user_id: str,
        current_context: Dict[str, Any],
        user_profile: Optional[UserProfile] = None
    ) -> Dict[str, Any]:
        """
        Get AI-powered suggestions based on current user context.

        Args:
            user_id: User requesting suggestions
            current_context: Current user context (active tools, tasks, etc.)
            user_profile: User profile for personalization

        Returns:
            Dictionary containing contextual suggestions
        """
        try:
            # Analyze current context
            context_analysis = await self._analyze_user_context(
                user_id, current_context
            )

            # Get executive function state
            focus_state = await self._assess_focus_state(
                user_id, context_analysis, user_profile
            )

            # Generate domain-specific suggestions
            suggestions = await self._generate_domain_suggestions(
                context_analysis, focus_state, user_profile
            )

            # Apply executive function accommodations
            suggestions = self._apply_executive_accommodations(
                suggestions, user_profile
            )

            return {
                'suggestions': suggestions,
                'focus_state': focus_state,
                'context_analysis': context_analysis,
                'timestamp': datetime.now().isoformat()
            }

        except Exception as e:
            logger.error(
                f"Failed to generate suggestions for user {user_id}: {e}")
            return {
                'suggestions': [],
                'error': str(e),
                'timestamp': datetime.now().isoformat()
            }

    async def break_down_task(
        self,
        user_id: str,
        task_description: str,
        domain: TaskDomain,
        complexity: TaskComplexity,
        user_profile: Optional[UserProfile] = None,
        additional_context: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """
        AI-powered task breakdown with executive function support.

        Args:
            user_id: User requesting breakdown
            task_description: Description of task to break down
            domain: Task domain for context
            complexity: Task complexity level
            user_profile: User profile for accommodations
            additional_context: Additional context for breakdown

        Returns:
            Structured task breakdown with steps and recommendations
        """
        try:
            # Create breakdown context
            breakdown_context = {
                'task_description': task_description,
                'domain': domain.value,
                'complexity': complexity.value,
                'user_accommodations': {},
                'domain_tools': self.domain_prompts.get(domain, {}).get('tools', []),
                'additional_context': additional_context or {}
            }

            # Apply user accommodations
            if user_profile:
                breakdown_context['user_accommodations'] = {
                    'adhd_accommodations': user_profile.adhd_accommodations,
                    'autism_accommodations': user_profile.autism_accommodations,
                    'focus_preferences': user_profile.focus_preferences
                }

            # Generate AI breakdown
            breakdown_prompt = self._create_breakdown_prompt(
                breakdown_context, domain
            )

            if self.llm_client:
                ai_response = await self.llm_client.generate_completion(
                    prompt=breakdown_prompt,
                    max_tokens=2000,
                    temperature=0.3
                )

                breakdown = self._parse_breakdown_response(ai_response)
            else:
                # Fallback breakdown without AI
                breakdown = self._generate_fallback_breakdown(
                    breakdown_context)

            # Optimize for executive function
            breakdown = self._optimize_for_executive_function(
                breakdown, user_profile
            )

            return breakdown

        except Exception as e:
            logger.error(f"Task breakdown failed: {e}")
            return {
                'steps': [],
                'error': str(e),
                'fallback_used': True
            }

    async def suggest_next_action(
        self,
        user_id: str,
        current_tasks: List[Task],
        user_profile: Optional[UserProfile] = None,
        time_available_minutes: Optional[int] = None,
        energy_level: str = "medium"
    ) -> Dict[str, Any]:
        """
        Suggest the next best action based on context and executive function state.

        Args:
            user_id: User requesting suggestion
            current_tasks: User's current tasks
            user_profile: User profile for personalization
            time_available_minutes: Available time for work
            energy_level: Current energy level (low, medium, high)

        Returns:
            Next action suggestion with reasoning
        """
        try:
            # Analyze task priorities and constraints
            task_analysis = self._analyze_task_priorities(
                current_tasks, time_available_minutes, energy_level
            )

            # Consider executive function factors
            executive_factors = self._assess_executive_factors(
                user_id, user_profile, current_tasks
            )

            # Generate recommendation
            recommendation = await self._generate_action_recommendation(
                task_analysis, executive_factors, user_profile
            )

            return {
                'recommended_action': recommendation,
                'reasoning': recommendation.get('reasoning', ''),
                'alternatives': recommendation.get('alternatives', []),
                'focus_tips': self._get_focus_tips(user_profile, energy_level),
                'estimated_benefit': recommendation.get('benefit_score', 0.5)
            }

        except Exception as e:
            logger.error(f"Next action suggestion failed: {e}")
            return {
                'recommended_action': {'type': 'rest', 'description': 'Take a break'},
                'error': str(e)
            }

