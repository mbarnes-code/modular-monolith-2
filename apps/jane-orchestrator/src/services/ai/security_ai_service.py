    def _parse_ai_correlation_response(
        self,
        ai_response: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Parse and validate AI correlation response."""
        try:
            response_data = ai_response.get('response', {})

            # Validate required fields
            required_fields = ['correlations', 'confidence']
            for field in required_fields:
                if field not in response_data:
                    logger.warning(f"AI response missing field: {field}")
                    response_data[field] = [
                    ] if field == 'correlations' else 0.0

            # Ensure confidence is within valid range
            confidence = response_data.get('confidence', 0.0)
            response_data['confidence'] = max(0.0, min(1.0, confidence))

            return response_data

        except Exception as e:
            logger.error(f"Failed to parse AI response: {e}")
            # Return minimal valid response
            return {
                'correlations': [],
                'confidence': 0.0,
                'attack_patterns': [],
                'recommendations': ['Manual analysis required'],
                'suggestions': []
            }

    def _generate_cache_key(self, indicators: List[str]) -> str:
        """Generate cache key for threat indicators."""
        # Sort indicators for consistent caching
        sorted_indicators = sorted(indicators)
        return f"correlation_{hash(tuple(sorted_indicators))}"

    def _is_cache_valid(self, cached_result: Dict[str, Any]) -> bool:
        """Check if cached result is still valid."""
        timestamp = cached_result.get('timestamp')
        ttl_minutes = cached_result.get('ttl_minutes', 15)

        if not timestamp:
            return False

        age_minutes = (datetime.now() - timestamp).total_seconds() / 60
        return age_minutes < ttl_minutes

