    async def create_security_session(
        self,
        user_id: UUID,
        security_profile: SecurityProfile,
        tools_requested: List[str]
    ) -> SecuritySession:
        """
        Create new security session for multi-tool operations.

        Args:
            user_id: User identifier
            security_profile: User's security profile
            tools_requested: List of tools to activate in session

        Returns:
            Created security session
        """
        start_time = datetime.now()

        try:
            # Validate requested tools
            validated_tools = await self._validate_tool_access(
                tools_requested, security_profile
            )

            # Create session
            session = SecuritySession(
                profile_id=security_profile.id,
                session_token=f"sec_{uuid4()}",
                tools_in_use=validated_tools,
                started_at=start_time,
                expires_at=datetime.now().replace(
                    minute=datetime.now().minute +
                    security_profile.session_timeout_minutes
                )
            )

            # Store active session
            self.active_sessions[session.id] = session

            # Log security activity
            session.log_activity(
                f"Security session created with tools: {validated_tools}"
            )

            # Update performance metrics
            processing_time = (
                datetime.now() - start_time).total_seconds() * 1000
            await self._record_performance_metric(processing_time)

            logger.info(
                f"Security session created: {session.id} with {len(validated_tools)} tools"
            )

            return session

        except Exception as e:
            logger.error(f"Failed to create security session: {e}")
            raise

    async def _validate_tool_access(
        self,
        tools_requested: List[str],
        security_profile: SecurityProfile
    ) -> List[str]:
        """Validate user access to requested tools."""
        validated_tools = []

        for tool_name in tools_requested:
            # Check tool permissions
            if security_profile.is_tool_available(tool_name):
                # Check tool status
                if self.tool_status.get(tool_name) == SecurityToolStatus.AVAILABLE:
                    validated_tools.append(tool_name)
                else:
                    logger.warning(
                        f"Tool {tool_name} requested but not available: "
                        f"{self.tool_status.get(tool_name)}"
                    )
            else:
                logger.warning(
                    f"Tool {tool_name} access denied for user {security_profile.user_id}"
                )

        return validated_tools

    async def execute_threat_hunting(
        self,
        session: SecuritySession,
        hunt_config: Dict[str, Any]
    ) -> Dict[str, Any]:
        """
        Execute threat hunting across multiple security tools.

        Args:
            session: Active security session
            hunt_config: Hunting configuration and parameters

        Returns:
            Hunting results from all applicable tools
        """
        start_time = datetime.now()

        try:
            # Validate hunt configuration
            await self._validate_hunt_config(hunt_config)

            # Determine tools to use for hunting
            hunting_tools = self._select_hunting_tools(
                session.tools_in_use, hunt_config
            )

            # Execute parallel hunting across tools
            hunting_tasks = []
            for tool_name in hunting_tools:
                task = self._execute_tool_hunt(tool_name, hunt_config)
                hunting_tasks.append(task)

            # Wait for all hunting tasks with timeout
            hunt_results = await asyncio.wait_for(
                asyncio.gather(*hunting_tasks, return_exceptions=True),
                timeout=self.max_response_time_ms / 1000
            )

            # Correlate results across tools
            correlated_results = await self._correlate_hunt_results(
                hunt_results, hunting_tools
            )

            # AI enhancement if enabled
            if any('ai_enhance' in tool for tool in hunting_tools):
                from ..data.models.ai_context import (AIEnhancementRequest,
                                                      AIEnhancementType)

                ai_request = AIEnhancementRequest(
                    tool_name='multi_tool_hunt',
                    domain='security',
                    enhancement_type=AIEnhancementType.PATTERN_RECOGNITION,
                    context_data={
                        'hunt_config': hunt_config,
                        'raw_results': hunt_results,
                        'tools_used': hunting_tools
                    }
                )

                # Get security profile for AI context
                security_profile = await self._get_security_profile_by_session(session)

                ai_enhancement = await self.ai_service.enhance_threat_correlation(
                    ai_request, security_profile
                )

                correlated_results['ai_enhancement'] = ai_enhancement.to_dict()

            # Update session activity
            session.log_activity("Threat hunting executed", "multi_tool")

            # Record performance
            processing_time = (
                datetime.now() - start_time).total_seconds() * 1000
            await self._record_performance_metric(processing_time)

            # Check constitutional compliance
            if processing_time > self.max_response_time_ms:
                logger.warning(
                    f"Threat hunting exceeded time limit: {processing_time}ms"
                )
                self.performance_metrics['constitutional_violations'] += 1

            return {
                'hunt_id': str(uuid4()),
                'results': correlated_results,
                'tools_used': hunting_tools,
                'processing_time_ms': processing_time,
                'constitutional_compliant': processing_time <= self.max_response_time_ms,
                'timestamp': datetime.now().isoformat()
            }

        except Exception as e:
            logger.error(f"Threat hunting failed: {e}")
            self.performance_metrics['failed_requests'] += 1

            # Return error response within time limits
            return {
                'hunt_id': str(uuid4()),
                'error': str(e),
                'tools_attempted': hunting_tools if 'hunting_tools' in locals() else [],
                'processing_time_ms': (datetime.now() - start_time).total_seconds() * 1000,
                'constitutional_compliant': False,
                'timestamp': datetime.now().isoformat()
            }

    async def _validate_hunt_config(self, hunt_config: Dict[str, Any]) -> None:
        """Validate threat hunting configuration."""
        required_fields = ['hunt_type', 'indicators']

        for field in required_fields:
            if field not in hunt_config:
                raise ValueError(
                    f"Missing required hunt config field: {field}")

        # Validate hunt type
        valid_hunt_types = [
            'ioc_search', 'pattern_analysis', 'behavioral_hunt',
            'timeline_analysis', 'correlation_hunt'
        ]

        if hunt_config['hunt_type'] not in valid_hunt_types:
            raise ValueError(f"Invalid hunt type: {hunt_config['hunt_type']}")

    def _select_hunting_tools(
        self,
        available_tools: List[str],
        hunt_config: Dict[str, Any]
    ) -> List[str]:
        """Select appropriate tools for hunting based on configuration."""
        hunt_type = hunt_config.get('hunt_type')

        # Tool selection based on hunt type
        tool_mapping = {
            'ioc_search': ['misp', 'helk', 'security_onion'],
            'pattern_analysis': ['yara_x', 'helk', 'maltrail'],
            'behavioral_hunt': ['helk', 'security_onion', 'nemesis'],
            'timeline_analysis': ['helk', 'security_onion'],
            'correlation_hunt': ['misp', 'helk', 'ai_enhance']
        }

        recommended_tools = tool_mapping.get(hunt_type, available_tools)

        # Filter by available tools
        selected_tools = [
            tool for tool in recommended_tools
            if tool in available_tools or tool == 'ai_enhance'
        ]

        return selected_tools

