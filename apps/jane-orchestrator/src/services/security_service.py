    async def _record_performance_metric(self, processing_time_ms: float) -> None:
        """Record performance metric for monitoring."""
        self.performance_metrics['total_requests'] += 1
        self.performance_metrics['response_times'].append(processing_time_ms)

        # Keep only last 1000 response times for memory efficiency
        if len(self.performance_metrics['response_times']) > 1000:
            self.performance_metrics['response_times'] = \
                self.performance_metrics['response_times'][-1000:]

        # Check constitutional compliance
        if processing_time_ms > self.max_response_time_ms:
            self.performance_metrics['constitutional_violations'] += 1

    async def get_performance_metrics(self) -> Dict[str, Any]:
        """Get security tools service performance metrics."""
        response_times = self.performance_metrics['response_times']

        if response_times:
            avg_response_time = sum(response_times) / len(response_times)
            max_response_time = max(response_times)
            min_response_time = min(response_times)
        else:
            avg_response_time = max_response_time = min_response_time = 0

        return {
            'total_requests': self.performance_metrics['total_requests'],
            'failed_requests': self.performance_metrics['failed_requests'],
            'constitutional_violations': self.performance_metrics['constitutional_violations'],
            'performance': {
                'avg_response_time_ms': avg_response_time,
                'max_response_time_ms': max_response_time,
                'min_response_time_ms': min_response_time,
                'constitutional_limit_ms': self.max_response_time_ms,
                'compliance_rate': (
                    (self.performance_metrics['total_requests'] -
                     self.performance_metrics['constitutional_violations']) /
                    max(self.performance_metrics['total_requests'], 1)
                )
            },
            'tool_status': self.tool_status,
            'active_sessions': len(self.active_sessions),
            'active_incidents': len(self.active_incidents),
            'timestamp': datetime.now().isoformat()
        }

