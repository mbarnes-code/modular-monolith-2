async def main():
    """Run the Security MCP Server."""
    # Configuration
    config = {
        'orchestrator_url': os.getenv('JANE_ORCHESTRATOR_URL', 'http://localhost:8000')
    }

    # Create and initialize server
    security_server = SecurityMCPServer(config)
    await security_server.initialize()

    # Create MCP server
    server = Server("security-mcp-server")

    # Register handlers
    @server.list_tools()
    async def handle_list_tools() -> ListToolsResult:
        tools = security_server.get_available_tools()
        return ListToolsResult(tools=tools)

    @server.call_tool()
    async def handle_call_tool(name: str, arguments: dict) -> CallToolResult:
        return await security_server.call_tool(name, arguments)

    @server.list_prompts()
    async def handle_list_prompts() -> ListPromptsResult:
        prompts = security_server.get_available_prompts()
        return ListPromptsResult(prompts=prompts)

    @server.get_prompt()
    async def handle_get_prompt(name: str, arguments: dict) -> GetPromptResult:
        return await security_server.get_prompt(name, arguments)

    @server.list_resources()
    async def handle_list_resources() -> ListResourcesResult:
        resources = security_server.get_available_resources()
        return ListResourcesResult(resources=resources)

    @server.read_resource()
    async def handle_read_resource(uri: str) -> ReadResourceResult:
        return await security_server.read_resource(uri)

    # Run server
    async with create_stdio_server(server) as (read_stream, write_stream):
        await server.run(read_stream, write_stream, server.create_initialization_options())


if __name__ == "__main__":
    asyncio.run(main())
