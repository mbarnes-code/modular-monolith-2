    async def call_tool(
        self, name: str, arguments: Dict[str, Any]
    ) -> CallToolResult:
        """Handle MCP tool calls."""
        start_time = datetime.now()

        try:
            result = None

            if name == "create_security_session":
                result = await self._create_security_session(arguments)

            elif name == "execute_threat_hunt":
                result = await self._execute_threat_hunt(arguments)

            elif name == "create_security_incident":
                result = await self._create_security_incident(arguments)

            elif name.startswith("query_"):
                tool_name = name[6:]  # Remove "query_" prefix
                result = await self._query_security_tool(tool_name, arguments)

            elif name == "get_security_performance":
                result = await self._get_security_performance()

            else:
                result = {"error": f"Unknown tool: {name}"}

            # Record performance
            processing_time = (
                (datetime.now() - start_time).total_seconds() * 1000
            )
            self.performance_metrics['total_requests'] += 1
            self.performance_metrics['response_times'].append(processing_time)

            # Check constitutional compliance (<1s for security domain)
            if processing_time > 1000:
                self.performance_metrics['constitutional_violations'] += 1
                logger.warning(
                    f"Tool call {name} exceeded 1s limit: {processing_time}ms"
                )

            return CallToolResult(
                content=[
                    TextContent(
                        type="text",
                        text=json.dumps({
                            **result,
                            "processing_time_ms": processing_time,
                            "constitutional_compliant": processing_time <= 1000
                        }, indent=2)
                    )
                ]
            )

        except Exception as e:
            logger.error(f"Tool call failed for {name}: {e}")
            processing_time = (
                (datetime.now() - start_time).total_seconds() * 1000
            )

            return CallToolResult(
                content=[
                    TextContent(
                        type="text",
                        text=json.dumps({
                            "error": str(e),
                            "processing_time_ms": processing_time,
                            "constitutional_compliant": processing_time <= 1000
                        }, indent=2)
                    )
                ],
                isError=True
            )

    async def _create_security_session(
        self,
        arguments: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Create security session via orchestrator."""
        try:
            response = await self.http_client.post(
                f"{self.orchestrator_url}/api/v1/security/sessions",
                json={
                    "tools_requested": arguments["tools"],
                    "operation_mode": arguments.get("operation_mode", "hybrid")
                }
            )

            if response.status_code == 201:
                session_data = response.json()
                self.current_session_id = session_data.get("session_id")

                return {
                    "success": True,
                    "session_id": self.current_session_id,
                    "tools_activated": session_data.get("tools_activated", []),
                    "message": "Security session created successfully"
                }
            else:
                return {
                    "success": False,
                    "error": (
                        f"Failed to create session: {response.status_code}"
                    ),
                    "details": response.text
                }

        except Exception as e:
            return {
                "success": False,
                "error": f"Session creation failed: {str(e)}"
            }

    async def _execute_threat_hunt(
        self,
        arguments: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Execute threat hunting via orchestrator."""
        if not self.current_session_id:
            return {
                "success": False,
                "error": "No active security session. Create session first."
            }

        try:
            response = await self.http_client.post(
                f"{self.orchestrator_url}/api/v1/security/sessions/"
                f"{self.current_session_id}/hunt",
                json={
                    "hunt_type": arguments["hunt_type"],
                    "indicators": arguments["indicators"],
                    "tools_filter": arguments.get("tools_filter"),
                    "ai_enhance": arguments.get("ai_enhance", True)
                }
            )

            if response.status_code == 200:
                hunt_data = response.json()

                return {
                    "success": True,
                    "hunt_id": hunt_data.get("hunt_id"),
                    "results": hunt_data.get("results", {}),
                    "tools_used": hunt_data.get("tools_used", []),
                    "ai_enhancement": hunt_data.get("ai_enhancement", {}),
                    "message": "Threat hunt completed successfully"
                }
            else:
                return {
                    "success": False,
                    "error": f"Threat hunt failed: {response.status_code}",
                    "details": response.text
                }

        except Exception as e:
            return {
                "success": False,
                "error": f"Threat hunt execution failed: {str(e)}"
            }

