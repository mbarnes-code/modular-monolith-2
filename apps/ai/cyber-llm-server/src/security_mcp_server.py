    async def _get_security_performance(self) -> Dict[str, Any]:
        """Get security performance metrics."""
        try:
            response = await self.http_client.get(
                f"{self.orchestrator_url}/api/v1/security/performance"
            )

            if response.status_code == 200:
                metrics = response.json()

                # Add MCP server metrics
                response_times = self.performance_metrics['response_times']
                if response_times:
                    avg_response_time = (
                        sum(response_times) / len(response_times)
                    )
                else:
                    avg_response_time = 0

                metrics['mcp_server'] = {
                    'total_requests': (
                        self.performance_metrics['total_requests']
                    ),
                    'avg_response_time_ms': avg_response_time,
                    'constitutional_violations': (
                        self.performance_metrics['constitutional_violations']
                    )
                }

                return {
                    "success": True,
                    "metrics": metrics
                }
            else:
                return {
                    "success": False,
                    "error": (
                        f"Failed to get performance metrics: "
                        f"{response.status_code}"
                    )
                }

        except Exception as e:
            return {
                "success": False,
                "error": f"Performance metrics request failed: {str(e)}"
            }

