#!/bin/bash
set -euo pipefail

# N8N SSO Setup Script
# This script configures N8N to use the central authentication service for SSO

echo "🚀 Setting up N8N SSO integration with central auth service..."
echo

# Configuration
AUTH_SERVICE_URL="${AUTH_SERVICE_URL:-http://localhost:3001}"
N8N_BASE_URL="${N8N_BASE_URL:-http://localhost:5678}"
N8N_PORT="${N8N_PORT:-5678}"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Helper functions
log_info() {
    echo -e "${BLUE}ℹ️  $1${NC}"
}

log_success() {
    echo -e "${GREEN}✅ $1${NC}"
}

log_warning() {
    echo -e "${YELLOW}⚠️  $1${NC}"
}

log_error() {
    echo -e "${RED}❌ $1${NC}"
}

# Check prerequisites
check_prerequisites() {
    log_info "Checking prerequisites..."
    
    # Check if Node.js is available
    if ! command -v node &> /dev/null; then
        log_error "Node.js is required but not installed"
        exit 1
    fi
    
    # Check if N8N is available
    if ! command -v n8n &> /dev/null && [ ! -f "node_modules/.bin/n8n" ]; then
        log_error "N8N is not installed. Please install N8N first."
        exit 1
    fi
    
    # Check if auth service is running
    if ! curl -s "${AUTH_SERVICE_URL}/health" &> /dev/null; then
        log_warning "Central auth service at ${AUTH_SERVICE_URL} is not accessible"
        log_warning "Make sure the auth service is running before starting N8N"
    else
        log_success "Central auth service is accessible"
    fi
}

# Install dependencies
install_dependencies() {
    log_info "Installing auth client dependencies..."
    
    if [ -f "package.json" ]; then
        # Add auth client dependencies if not already present
        if ! grep -q "@modular-monolith/auth-clients" package.json; then
            log_info "Adding auth client dependency..."
            npm install @modular-monolith/auth-clients@^1.0.0
        fi
        
        if ! grep -q "typescript" package.json; then
            log_info "Adding TypeScript for configuration..."
            npm install --save-dev typescript @types/node
        fi
    fi
}

# Generate SSL certificates for development (if needed)
setup_ssl() {
    if [ "${N8N_PROTOCOL:-http}" = "https" ]; then
        log_info "Setting up SSL certificates for HTTPS..."
        
        if [ ! -f "certs/server.crt" ]; then
            mkdir -p certs
            
            # Generate self-signed certificate for development
            openssl req -x509 -nodes -days 365 -newkey rsa:2048 \
                -keyout certs/server.key \
                -out certs/server.crt \
                -subj "/CN=localhost/O=N8N Development"
                
            log_success "SSL certificates generated"
        fi
    fi
}

# Register N8N as OAuth2 client
register_oauth_client() {
    log_info "Registering N8N as OAuth2 client..."
    
    if [ -z "${AUTH_SERVICE_ADMIN_API_KEY:-}" ]; then
        log_warning "AUTH_SERVICE_ADMIN_API_KEY not set"
        log_warning "Please register N8N manually or provide admin API key"
        return
    fi
    
    # Use the registration script
    if [ -f "register-n8n-client.js" ]; then
        AUTH_SERVICE_URL="${AUTH_SERVICE_URL}" \
        N8N_BASE_URL="${N8N_BASE_URL}" \
        AUTH_SERVICE_ADMIN_API_KEY="${AUTH_SERVICE_ADMIN_API_KEY}" \
        node register-n8n-client.js
        
        log_success "OAuth2 client registration completed"
    else
        log_error "Client registration script not found"
    fi
}

# Create N8N configuration
create_n8n_config() {
    log_info "Creating N8N SSO configuration..."
    
    # Create .env file for N8N
    cat > .env.sso << EOF
# N8N SSO Configuration
# Generated by setup script on $(date)

# Basic N8N Configuration
N8N_HOST=0.0.0.0
N8N_PORT=${N8N_PORT}
N8N_PROTOCOL=${N8N_PROTOCOL:-http}
N8N_BASE_URL=${N8N_BASE_URL}
WEBHOOK_URL=${N8N_BASE_URL}

# Authentication Configuration
N8N_USER_MANAGEMENT_AUTHENTICATION_METHOD=oidc
N8N_SSO_ENABLED=true

# Central Auth Service Configuration
AUTH_SERVICE_URL=${AUTH_SERVICE_URL}

# OAuth2/OIDC Configuration (set after client registration)
# N8N_OIDC_CLIENT_ID=n8n-service
# N8N_OIDC_CLIENT_SECRET=your-client-secret

# Database Configuration (required for user management)
DB_TYPE=postgresdb
DB_POSTGRESDB_HOST=${DB_HOST:-localhost}
DB_POSTGRESDB_PORT=${DB_PORT:-5432}
DB_POSTGRESDB_DATABASE=${DB_NAME:-n8n}
DB_POSTGRESDB_USER=${DB_USER:-n8n_user}
DB_POSTGRESDB_PASSWORD=${DB_PASSWORD:-n8n_password}

# Redis Configuration (for sessions)
REDIS_HOST=${REDIS_HOST:-localhost}
REDIS_PORT=${REDIS_PORT:-6379}
REDIS_PASSWORD=${REDIS_PASSWORD:-}
REDIS_DB=${REDIS_DB:-1}

# Security Configuration
N8N_JWT_AUTH_HEADER_NAME=authorization
N8N_JWT_AUTH_HEADER_PREFIX=Bearer

# Log Configuration
N8N_LOG_LEVEL=${N8N_LOG_LEVEL:-info}
EOF

    log_success "N8N SSO configuration created in .env.sso"
}

# Create docker-compose override for SSO
create_docker_compose() {
    log_info "Creating docker-compose override for SSO..."
    
    cat > docker-compose.sso.yml << EOF
version: '3.8'

services:
  n8n:
    environment:
      # SSO Configuration
      - N8N_USER_MANAGEMENT_AUTHENTICATION_METHOD=oidc
      - N8N_SSO_ENABLED=true
      - AUTH_SERVICE_URL=${AUTH_SERVICE_URL}
      
      # OAuth2 Configuration (update after client registration)
      # - N8N_OIDC_CLIENT_ID=n8n-service
      # - N8N_OIDC_CLIENT_SECRET=your-client-secret
    
    depends_on:
      - postgres
      - redis
    
    networks:
      - n8n-network
      - auth-network  # Connect to central auth service

  # Ensure required services are available
  postgres:
    image: postgres:15
    environment:
      POSTGRES_DB: n8n
      POSTGRES_USER: n8n_user
      POSTGRES_PASSWORD: n8n_password
    volumes:
      - n8n_postgres_data:/var/lib/postgresql/data
    networks:
      - n8n-network

  redis:
    image: redis:7-alpine
    command: redis-server --appendonly yes
    volumes:
      - n8n_redis_data:/data
    networks:
      - n8n-network

volumes:
  n8n_postgres_data:
  n8n_redis_data:

networks:
  n8n-network:
    driver: bridge
  auth-network:
    external: true  # Connect to central auth service network
EOF

    log_success "Docker Compose SSO configuration created"
}

# Validate configuration
validate_config() {
    log_info "Validating N8N SSO configuration..."
    
    # Check if required files exist
    local files=(".env.sso" "n8n-auth-integration.ts" "n8n-auth-patch.ts")
    for file in "${files[@]}"; do
        if [ ! -f "$file" ]; then
            log_error "Required file $file not found"
            return 1
        fi
    done
    
    # Compile TypeScript configuration
    if command -v npx &> /dev/null; then
        log_info "Compiling TypeScript configuration..."
        npx tsc --noEmit n8n-auth-integration.ts n8n-auth-patch.ts
        log_success "TypeScript configuration is valid"
    fi
    
    log_success "Configuration validation completed"
}

# Main setup process
main() {
    echo "N8N SSO Setup Configuration:"
    echo "  Auth Service: ${AUTH_SERVICE_URL}"
    echo "  N8N Base URL: ${N8N_BASE_URL}"
    echo "  N8N Port: ${N8N_PORT}"
    echo
    
    # Run setup steps
    check_prerequisites
    install_dependencies
    setup_ssl
    create_n8n_config
    create_docker_compose
    
    # Register OAuth client if API key is provided
    if [ -n "${AUTH_SERVICE_ADMIN_API_KEY:-}" ]; then
        register_oauth_client
    else
        log_warning "AUTH_SERVICE_ADMIN_API_KEY not provided"
        log_warning "Run the following to register N8N as OAuth client:"
        echo "  AUTH_SERVICE_ADMIN_API_KEY=your-key node register-n8n-client.js"
    fi
    
    validate_config
    
    echo
    log_success "N8N SSO setup completed successfully!"
    echo
    echo "Next steps:"
    echo "1. Update .env.sso with your OAuth2 client credentials"
    echo "2. Start your services:"
    echo "   docker-compose -f docker-compose.yml -f docker-compose.sso.yml up -d"
    echo "3. Access N8N at: ${N8N_BASE_URL}"
    echo "4. Use SSO login via central auth service"
    echo
}

# Handle script arguments
case "${1:-setup}" in
    "setup")
        main
        ;;
    "register-client")
        register_oauth_client
        ;;
    "validate")
        validate_config
        ;;
    "help")
        echo "N8N SSO Setup Script"
        echo
        echo "Usage: $0 [command]"
        echo
        echo "Commands:"
        echo "  setup          - Run full SSO setup (default)"
        echo "  register-client - Register N8N as OAuth2 client only"
        echo "  validate       - Validate configuration only"
        echo "  help          - Show this help message"
        echo
        echo "Environment Variables:"
        echo "  AUTH_SERVICE_URL           - Central auth service URL"
        echo "  AUTH_SERVICE_ADMIN_API_KEY - Admin API key for client registration"
        echo "  N8N_BASE_URL              - N8N base URL"
        echo "  N8N_PORT                  - N8N port number"
        ;;
    *)
        log_error "Unknown command: $1"
        echo "Use '$0 help' for usage information"
        exit 1
        ;;
esac