"""
LLM Integration Configuration and Service Registry

This module provides configuration and service registration for LLM integration
across all domain-specific AI servers (cyber, MTG, infrastructure, code).

Constitutional Requirements:
- Domain-specific AI server routing
- Performance monitoring and fallback
- Executive function accommodation support

Author: Generated by Phase 5 implementation
Created: 2025-10-28
"""

import logging
from dataclasses import dataclass
from typing import Dict, Optional

from ...data.models.task import TaskDomain
from .client import LLMClient, LLMConnectionPool

logger = logging.getLogger(__name__)


@dataclass
class LLMServerConfig:
    """Configuration for domain-specific LLM servers."""

    name: str
    base_url: str
    specialization: str
    performance_target_ms: int
    fallback_available: bool = True
    max_retries: int = 3
    timeout_seconds: int = 30


class LLMServiceRegistry:
    """
    Registry for domain-specific LLM services.

    Manages connections to specialized AI servers:
    - cyber-llm-server: Security domain AI
    - mtg-llm-server: MTG domain AI  
    - infrastructure-llm-server: Infrastructure domain AI
    - code-llm-server: Development and coding AI
    """

    def __init__(self):
        """Initialize LLM service registry."""
        self.servers: Dict[TaskDomain, LLMServerConfig] = {}
        self.clients: Dict[TaskDomain, LLMClient] = {}
        self.connection_pools: Dict[TaskDomain, LLMConnectionPool] = {}

        # Initialize default server configurations
        self._setup_default_configurations()

    def _setup_default_configurations(self):
        """Setup default LLM server configurations."""

        # Security domain AI server
        self.servers[TaskDomain.SECURITY] = LLMServerConfig(
            name="cyber-llm-server",
            base_url="http://localhost:8001",
            specialization="cybersecurity analysis and threat management",
            performance_target_ms=1000,  # <1s for security domain
            fallback_available=True,
            max_retries=2,  # Faster retries for security
            timeout_seconds=1
        )

        # Productivity domain (general purpose)
        self.servers[TaskDomain.PRODUCTIVITY] = LLMServerConfig(
            name="productivity-llm-server",
            base_url="http://localhost:8002",
            specialization="task management and workflow optimization",
            performance_target_ms=2000,  # <2s for productivity domain
            fallback_available=True,
            max_retries=3,
            timeout_seconds=2
        )

        # MTG domain AI server
        self.servers[TaskDomain.MTG] = LLMServerConfig(
            name="mtg-llm-server",
            base_url="http://localhost:8003",
            specialization="Magic: The Gathering strategy and deck building",
            performance_target_ms=3000,  # <3s for MTG domain
            fallback_available=True,
            max_retries=3,
            timeout_seconds=3
        )

        # Infrastructure domain AI server
        self.servers[TaskDomain.INFRASTRUCTURE] = LLMServerConfig(
            name="infrastructure-llm-server",
            base_url="http://localhost:8004",
            specialization="system administration and DevOps",
            performance_target_ms=5000,  # <5s for infrastructure domain
            fallback_available=True,
            max_retries=3,
            timeout_seconds=5
        )

    def register_server(
        self,
        domain: TaskDomain,
        config: LLMServerConfig
    ):
        """Register a new LLM server for a domain."""
        self.servers[domain] = config
        logger.info(f"Registered LLM server for {domain.value}: {config.name}")

    def get_client(self, domain: TaskDomain) -> Optional[LLMClient]:
        """Get LLM client for a specific domain."""
        if domain not in self.clients:
            config = self.servers.get(domain)
            if not config:
                logger.warning(
                    f"No LLM server configured for domain {domain.value}")
                return None

            # Create client with domain-specific configuration
            self.clients[domain] = LLMClient(
                base_url=config.base_url,
                timeout_seconds=config.timeout_seconds,
                max_retries=config.max_retries
            )

        return self.clients[domain]

    def get_fallback_client(self) -> LLMClient:
        """Get fallback LLM client (productivity server)."""
        return self.get_client(TaskDomain.PRODUCTIVITY)

    async def health_check_all(self) -> Dict[str, bool]:
        """Check health of all registered LLM servers."""
        results = {}

        for domain, config in self.servers.items():
            try:
                client = self.get_client(domain)
                if client:
                    healthy = await client.health_check()
                    results[f"{domain.value}_{config.name}"] = healthy
                else:
                    results[f"{domain.value}_{config.name}"] = False
            except Exception as e:
                logger.error(f"Health check failed for {domain.value}: {e}")
                results[f"{domain.value}_{config.name}"] = False

        return results

    def get_server_info(self, domain: TaskDomain) -> Optional[Dict[str, str]]:
        """Get server information for a domain."""
        config = self.servers.get(domain)
        if not config:
            return None

        return {
            "name": config.name,
            "base_url": config.base_url,
            "specialization": config.specialization,
            "performance_target_ms": str(config.performance_target_ms),
            "status": "available" if config.fallback_available else "limited"
        }

    async def close_all_connections(self):
        """Close all LLM client connections."""
        for client in self.clients.values():
            if client.session:
                await client.session.close()

        for pool in self.connection_pools.values():
            await pool.close_all()


class LLMIntegrationService:
    """
    High-level service for LLM integration across all domains.

    Provides unified interface for AI assistance with automatic
    domain routing and fallback handling.
    """

    def __init__(self, registry: Optional[LLMServiceRegistry] = None):
        """Initialize LLM integration service."""
        self.registry = registry or LLMServiceRegistry()

    async def enhance_request(
        self,
        prompt: str,
        domain: TaskDomain,
        request_type: str = "completion",
        context: Optional[Dict] = None
    ) -> Dict:
        """
        Enhanced request with domain-specific routing and fallback.

        Args:
            prompt: Input prompt for AI
            domain: Target domain for specialized AI
            request_type: Type of request (completion, breakdown, etc.)
            context: Additional context for the request

        Returns:
            AI response with metadata
        """
        try:
            # Get domain-specific client
            client = self.registry.get_client(domain)

            if not client:
                logger.warning(
                    f"No client for domain {domain.value}, using fallback")
                client = self.registry.get_fallback_client()

            # Generate completion with domain awareness
            async with client:
                response_text = await client.generate_completion(
                    prompt=prompt,
                    domain=domain,
                    max_tokens=context.get(
                        'max_tokens', 1000) if context else 1000,
                    temperature=context.get(
                        'temperature', 0.7) if context else 0.7
                )

            return {
                "response": response_text,
                "domain": domain.value,
                "server": self.registry.servers[domain].name,
                "success": True,
                "fallback_used": client == self.registry.get_fallback_client()
            }

        except Exception as e:
            logger.error(f"LLM request failed for domain {domain.value}: {e}")

            # Try fallback if not already using it
            if client != self.registry.get_fallback_client():
                try:
                    fallback_client = self.registry.get_fallback_client()
                    async with fallback_client:
                        response_text = await fallback_client.generate_completion(
                            prompt=prompt,
                            max_tokens=500,
                            temperature=0.5
                        )

                    return {
                        "response": response_text,
                        "domain": domain.value,
                        "server": "fallback",
                        "success": True,
                        "fallback_used": True,
                        "original_error": str(e)
                    }

                except Exception as fallback_error:
                    logger.error(f"Fallback also failed: {fallback_error}")

            # Return error response
            return {
                "response": "",
                "domain": domain.value,
                "server": "none",
                "success": False,
                "fallback_used": True,
                "error": str(e)
            }

    async def get_domain_capabilities(
        self,
        domain: TaskDomain
    ) -> Dict[str, str]:
        """Get capabilities information for a domain."""
        server_info = self.registry.get_server_info(domain)

        if not server_info:
            return {
                "domain": domain.value,
                "status": "not_configured",
                "capabilities": []
            }

        capabilities = {
            TaskDomain.SECURITY: [
                "threat_analysis",
                "vulnerability_assessment",
                "incident_response",
                "malware_analysis",
                "forensic_investigation"
            ],
            TaskDomain.PRODUCTIVITY: [
                "task_breakdown",
                "workflow_optimization",
                "time_management",
                "priority_analysis",
                "executive_function_support"
            ],
            TaskDomain.MTG: [
                "deck_analysis",
                "card_recommendations",
                "combo_detection",
                "meta_analysis",
                "rules_clarification"
            ],
            TaskDomain.INFRASTRUCTURE: [
                "system_monitoring",
                "deployment_automation",
                "troubleshooting",
                "capacity_planning",
                "security_hardening"
            ]
        }

        return {
            "domain": domain.value,
            "status": "available",
            "server": server_info["name"],
            "specialization": server_info["specialization"],
            "capabilities": capabilities.get(domain, []),
            "performance_target": server_info["performance_target_ms"]
        }

    async def health_check(self) -> Dict[str, Dict]:
        """Comprehensive health check of all LLM services."""
        health_results = await self.registry.health_check_all()

        status_summary = {
            "overall_status": "healthy" if all(health_results.values()) else "degraded",
            "servers": {},
            "timestamp": str(logger.handlers[0].formatter.formatTime(
                logging.LogRecord(
                    name="", level=0, pathname="", lineno=0,
                    msg="", args=(), exc_info=None
                )
            ) if logger.handlers else "unknown")
        }

        # Organize by domain
        for domain in TaskDomain:
            server_key = f"{domain.value}_{self.registry.servers.get(domain, LLMServerConfig('', '', '', 0)).name}"
            server_healthy = health_results.get(server_key, False)

            status_summary["servers"][domain.value] = {
                "healthy": server_healthy,
                "server_name": self.registry.servers.get(domain, LLMServerConfig('', '', '', 0)).name,
                "specialization": self.registry.servers.get(domain, LLMServerConfig('', '', '', 0)).specialization
            }

        return status_summary


# Global registry instance
_global_registry: Optional[LLMServiceRegistry] = None


def get_llm_registry() -> LLMServiceRegistry:
    """Get global LLM service registry instance."""
    global _global_registry

    if _global_registry is None:
        _global_registry = LLMServiceRegistry()

    return _global_registry


def get_llm_service() -> LLMIntegrationService:
    """Get LLM integration service instance."""
    return LLMIntegrationService(get_llm_registry())
