"""
LLM Client for vLLM Integration

This module provides a client for connecting to vLLM servers for AI-powered
task management assistance across all 37 integrated tools.

Constitutional Requirements:
- Domain-specific performance targets
- Fallback mechanisms for AI failures
- Context-aware prompt generation
- Executive function accommodation support

Author: Generated by Phase 5 implementation
Created: 2025-10-28
"""

import asyncio
import json
import logging
from datetime import datetime
from typing import Any, Dict, List, Optional
from urllib.parse import urljoin

import aiohttp
from aiohttp import ClientSession, ClientTimeout

from ...data.models.task import DOMAIN_PERFORMANCE_TARGETS, TaskDomain

logger = logging.getLogger(__name__)


class LLMClient:
    """
    Client for vLLM server integration.

    Provides AI capabilities for:
    - Task breakdown and planning
    - Executive function support
    - Cross-tool context awareness
    - Domain-specific assistance
    """

    def __init__(
        self,
        base_url: str = "http://localhost:8000",
        timeout_seconds: int = 30,
        max_retries: int = 3
    ):
        """Initialize LLM client."""
        self.base_url = base_url.rstrip('/')
        self.timeout = ClientTimeout(total=timeout_seconds)
        self.max_retries = max_retries
        self.session: Optional[ClientSession] = None

        # Domain-specific model endpoints
        self.domain_endpoints = {
            TaskDomain.SECURITY: f"{self.base_url}/v1/completions",
            TaskDomain.PRODUCTIVITY: f"{self.base_url}/v1/completions",
            TaskDomain.MTG: f"{self.base_url}/v1/completions",
            TaskDomain.INFRASTRUCTURE: f"{self.base_url}/v1/completions",
        }

    async def __aenter__(self):
        """Async context manager entry."""
        self.session = ClientSession(timeout=self.timeout)
        return self

    async def __aexit__(self, exc_type, exc_val, exc_tb):
        """Async context manager exit."""
        if self.session:
            await self.session.close()

    async def generate_completion(
        self,
        prompt: str,
        domain: Optional[TaskDomain] = None,
        max_tokens: int = 1000,
        temperature: float = 0.7,
        stop_sequences: Optional[List[str]] = None
    ) -> str:
        """
        Generate text completion using vLLM.

        Args:
            prompt: Input prompt for generation
            domain: Domain context for model selection
            max_tokens: Maximum tokens to generate
            temperature: Generation temperature (0-1)
            stop_sequences: Stop sequences for generation

        Returns:
            Generated text completion
        """
        if not self.session:
            self.session = ClientSession(timeout=self.timeout)

        # Select endpoint based on domain
        endpoint = self.domain_endpoints.get(
            domain, f"{self.base_url}/v1/completions"
        )

        # Prepare request payload
        payload = {
            "prompt": prompt,
            "max_tokens": max_tokens,
            "temperature": temperature,
            "stop": stop_sequences or [],
            "echo": False,
            "stream": False
        }

        # Apply domain-specific timeout
        domain_timeout = None
        if domain:
            domain_timeout = DOMAIN_PERFORMANCE_TARGETS.get(
                domain, 30000) / 1000

        for attempt in range(self.max_retries):
            try:
                start_time = datetime.now()

                async with self.session.post(
                    endpoint,
                    json=payload,
                    timeout=ClientTimeout(total=domain_timeout or 30)
                ) as response:
                    if response.status == 200:
                        result = await response.json()

                        # Log performance
                        duration = (datetime.now() -
                                    start_time).total_seconds() * 1000
                        target = DOMAIN_PERFORMANCE_TARGETS.get(domain, 30000)

                        logger.info(
                            f"LLM completion: {duration:.0f}ms "
                            f"(target: {target}ms, domain: {domain})"
                        )

                        return result["choices"][0]["text"].strip()
                    else:
                        error_text = await response.text()
                        logger.error(
                            f"LLM request failed (attempt {attempt + 1}): "
                            f"{response.status} - {error_text}"
                        )

            except asyncio.TimeoutError:
                logger.warning(
                    f"LLM request timeout (attempt {attempt + 1}): "
                    f"domain {domain}, timeout {domain_timeout}s"
                )

            except Exception as e:
                logger.error(f"LLM request error (attempt {attempt + 1}): {e}")

            # Wait before retry
            if attempt < self.max_retries - 1:
                await asyncio.sleep(2 ** attempt)  # Exponential backoff

        # All retries failed
        raise RuntimeError(
            f"LLM completion failed after {self.max_retries} attempts")

    async def generate_task_breakdown(
        self,
        task_description: str,
        domain: TaskDomain,
        complexity: str,
        user_accommodations: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """
        Generate structured task breakdown.

        Args:
            task_description: Description of task to break down
            domain: Task domain for context
            complexity: Task complexity level
            user_accommodations: User executive function accommodations

        Returns:
            Structured task breakdown with steps
        """
        prompt = self._create_breakdown_prompt(
            task_description, domain, complexity, user_accommodations
        )

        try:
            response_text = await self.generate_completion(
                prompt=prompt,
                domain=domain,
                max_tokens=1500,
                temperature=0.3,
                stop_sequences=["END_BREAKDOWN"]
            )

            # Parse JSON response
            breakdown = json.loads(response_text)

            # Validate structure
            if not isinstance(breakdown, dict) or "steps" not in breakdown:
                raise ValueError("Invalid breakdown structure")

            return breakdown

        except (json.JSONDecodeError, ValueError) as e:
            logger.error(f"Failed to parse breakdown response: {e}")

            # Return fallback breakdown
            return self._create_fallback_breakdown(task_description, complexity)

    async def generate_contextual_suggestions(
        self,
        user_context: Dict[str, Any],
        domain: Optional[TaskDomain] = None
    ) -> List[Dict[str, Any]]:
        """
        Generate contextual suggestions based on user state.

        Args:
            user_context: Current user context (tools, tasks, focus state)
            domain: Primary domain for suggestions

        Returns:
            List of contextual suggestions
        """
        prompt = self._create_suggestions_prompt(user_context, domain)

        try:
            response_text = await self.generate_completion(
                prompt=prompt,
                domain=domain,
                max_tokens=1000,
                temperature=0.5,
                stop_sequences=["END_SUGGESTIONS"]
            )

            # Parse JSON response
            suggestions = json.loads(response_text)

            if not isinstance(suggestions, list):
                suggestions = suggestions.get("suggestions", [])

            return suggestions

        except (json.JSONDecodeError, ValueError) as e:
            logger.error(f"Failed to parse suggestions: {e}")
            return []

    async def optimize_work_session(
        self,
        tasks: List[Dict[str, Any]],
        duration_minutes: int,
        user_accommodations: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """
        Generate optimized work session plan.

        Args:
            tasks: List of tasks to include in session
            duration_minutes: Planned session duration
            user_accommodations: User executive function accommodations

        Returns:
            Optimized session plan with timing and breaks
        """
        prompt = self._create_session_optimization_prompt(
            tasks, duration_minutes, user_accommodations
        )

        try:
            response_text = await self.generate_completion(
                prompt=prompt,
                max_tokens=1200,
                temperature=0.4,
                stop_sequences=["END_SESSION_PLAN"]
            )

            # Parse JSON response
            session_plan = json.loads(response_text)

            # Validate structure
            if not isinstance(session_plan, dict):
                raise ValueError("Invalid session plan structure")

            return session_plan

        except (json.JSONDecodeError, ValueError) as e:
            logger.error(f"Failed to parse session plan: {e}")

            # Return simple fallback plan
            return {
                "pattern": "pomodoro",
                "duration_minutes": duration_minutes,
                "work_blocks": [
                    {"duration": 25, "task": "Focus work"},
                    {"duration": 5, "task": "Break"}
                ],
                "fallback_used": True
            }

    async def health_check(self) -> bool:
        """Check if LLM server is healthy."""
        if not self.session:
            self.session = ClientSession(timeout=self.timeout)

        try:
            async with self.session.get(f"{self.base_url}/health") as response:
                return response.status == 200
        except Exception as e:
            logger.error(f"LLM health check failed: {e}")
            return False

    # Private helper methods

    def _create_breakdown_prompt(
        self,
        task_description: str,
        domain: TaskDomain,
        complexity: str,
        user_accommodations: Optional[Dict[str, Any]]
    ) -> str:
        """Create prompt for task breakdown generation."""
        domain_context = {
            TaskDomain.SECURITY: "cybersecurity analysis and threat management",
            TaskDomain.PRODUCTIVITY: "task management and workflow optimization",
            TaskDomain.MTG: "Magic: The Gathering strategy and deck building",
            TaskDomain.INFRASTRUCTURE: "system administration and DevOps"
        }.get(domain, "general task management")

        accommodations_text = ""
        if user_accommodations:
            adhd = user_accommodations.get('adhd_accommodations', {})
            autism = user_accommodations.get('autism_accommodations', {})

            if adhd.get('task_breakdown'):
                accommodations_text += "- Break into very small, specific steps\n"
            if adhd.get('time_awareness'):
                accommodations_text += "- Include time estimates for each step\n"
            if autism.get('detailed_descriptions'):
                accommodations_text += "- Provide detailed, unambiguous descriptions\n"
            if autism.get('predictable_patterns'):
                accommodations_text += "- Follow consistent step patterns\n"

        prompt = f"""You are an AI assistant specialized in {domain_context}. 
Break down the following task for a user with executive function needs:

Task: {task_description}
Complexity: {complexity}
Domain: {domain.value if domain else 'general'}

User Accommodations:
{accommodations_text or "- Standard breakdown approach"}

Provide a JSON response with this structure:
{{
    "steps": [
        {{
            "title": "Step title",
            "description": "Detailed description",
            "estimated_minutes": 15,
            "required_tool": "tool name or null",
            "depends_on": [],
            "can_run_parallel": false
        }}
    ],
    "confidence": 0.8,
    "total_estimated_minutes": 60,
    "break_points": [2, 4]
}}

Generate 3-7 steps maximum. Be specific and actionable.

END_BREAKDOWN"""

        return prompt.strip()

    def _create_suggestions_prompt(
        self,
        user_context: Dict[str, Any],
        domain: Optional[TaskDomain]
    ) -> str:
        """Create prompt for contextual suggestions."""
        active_tools = user_context.get('active_tools', [])
        context_switches = user_context.get('context_switches', 0)
        focus_level = user_context.get('focus_level', 'medium')

        prompt = f"""You are an AI assistant for executive function support.
Generate contextual suggestions based on the user's current state:

Active Tools: {', '.join(active_tools) if active_tools else 'None'}
Context Switches: {context_switches}
Focus Level: {focus_level}
Primary Domain: {domain.value if domain else 'general'}

Generate 3-5 helpful suggestions as JSON:
[
    {{
        "type": "tool_optimization",
        "title": "Suggestion title",
        "description": "Detailed description",
        "priority": 0.8,
        "estimated_time": 15,
        "reasoning": "Why this suggestion is helpful"
    }}
]

Focus on executive function support and cognitive load reduction.

END_SUGGESTIONS"""

        return prompt.strip()

    def _create_session_optimization_prompt(
        self,
        tasks: List[Dict[str, Any]],
        duration_minutes: int,
        user_accommodations: Optional[Dict[str, Any]]
    ) -> str:
        """Create prompt for session optimization."""
        tasks_text = "\n".join([
            f"- {task.get('title', 'Untitled')} ({task.get('complexity', 'medium')} complexity)"
            for task in tasks[:5]  # Limit to 5 tasks for prompt length
        ])

        accommodations_text = ""
        if user_accommodations:
            adhd = user_accommodations.get('adhd_accommodations', {})
            if adhd.get('short_focus_periods'):
                accommodations_text += "- Use shorter focus blocks (15-20 minutes)\n"
            if adhd.get('frequent_breaks'):
                accommodations_text += "- Include frequent breaks\n"

        prompt = f"""Optimize a work session for executive function support.

Session Duration: {duration_minutes} minutes
Tasks:
{tasks_text}

User Accommodations:
{accommodations_text or "- Standard session structure"}

Generate an optimized session plan as JSON:
{{
    "pattern": "pomodoro",
    "work_blocks": [
        {{
            "type": "work",
            "duration": 25,
            "task": "Specific task or task portion",
            "focus_tips": ["tip1", "tip2"]
        }},
        {{
            "type": "break", 
            "duration": 5,
            "activity": "Stretch and hydrate"
        }}
    ],
    "total_duration": {duration_minutes},
    "break_frequency": 5,
    "contingency_plan": "What to do if focus drops"
}}

Optimize for sustained focus and minimal context switching.

END_SESSION_PLAN"""

        return prompt.strip()

    def _create_fallback_breakdown(
        self,
        task_description: str,
        complexity: str
    ) -> Dict[str, Any]:
        """Create fallback breakdown when AI fails."""
        if complexity == "simple":
            steps = [
                {
                    "title": "Complete Task",
                    "description": task_description,
                    "estimated_minutes": 15,
                    "required_tool": None,
                    "depends_on": [],
                    "can_run_parallel": False
                }
            ]
        else:
            steps = [
                {
                    "title": "Plan and Research",
                    "description": "Review requirements and gather information",
                    "estimated_minutes": 20,
                    "required_tool": None,
                    "depends_on": [],
                    "can_run_parallel": False
                },
                {
                    "title": "Execute Main Work",
                    "description": f"Complete: {task_description}",
                    "estimated_minutes": 40,
                    "required_tool": None,
                    "depends_on": [1],
                    "can_run_parallel": False
                },
                {
                    "title": "Review and Finalize",
                    "description": "Review work and finalize deliverables",
                    "estimated_minutes": 15,
                    "required_tool": None,
                    "depends_on": [2],
                    "can_run_parallel": False
                }
            ]

        return {
            "steps": steps,
            "confidence": 0.6,
            "total_estimated_minutes": sum(s["estimated_minutes"] for s in steps),
            "break_points": [len(steps) // 2] if len(steps) > 2 else [],
            "fallback_used": True
        }


class LLMConnectionPool:
    """
    Connection pool for managing multiple LLM clients.

    Provides load balancing and failover across multiple vLLM servers.
    """

    def __init__(self, endpoints: List[str], max_connections: int = 10):
        """Initialize connection pool."""
        self.endpoints = endpoints
        self.max_connections = max_connections
        self.clients: List[LLMClient] = []
        self.current_index = 0

        # Initialize clients
        for endpoint in endpoints:
            self.clients.append(LLMClient(base_url=endpoint))

    async def get_client(self) -> LLMClient:
        """Get next available client using round-robin."""
        client = self.clients[self.current_index]
        self.current_index = (self.current_index + 1) % len(self.clients)
        return client

    async def health_check_all(self) -> Dict[str, bool]:
        """Check health of all clients."""
        results = {}

        for i, client in enumerate(self.clients):
            endpoint = self.endpoints[i]
            try:
                healthy = await client.health_check()
                results[endpoint] = healthy
            except Exception as e:
                logger.error(f"Health check failed for {endpoint}: {e}")
                results[endpoint] = False

        return results

    async def close_all(self):
        """Close all client connections."""
        for client in self.clients:
            if client.session:
                await client.session.close()


# Factory function for creating LLM clients
def create_llm_client(
    base_url: Optional[str] = None,
    timeout_seconds: int = 30,
    max_retries: int = 3
) -> LLMClient:
    """
    Factory function to create LLM client.

    Args:
        base_url: vLLM server base URL
        timeout_seconds: Request timeout
        max_retries: Maximum retry attempts

    Returns:
        Configured LLM client
    """
    default_url = "http://localhost:8000"

    return LLMClient(
        base_url=base_url or default_url,
        timeout_seconds=timeout_seconds,
        max_retries=max_retries
    )
