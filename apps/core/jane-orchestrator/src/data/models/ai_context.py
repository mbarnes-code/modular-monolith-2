class AIContextStatus(str, Enum):
    """Status of AI context processing."""

    PENDING = "pending"
    PROCESSING = "processing"
    COMPLETED = "completed"
    FAILED = "failed"
    TIMEOUT = "timeout"


class AIEnhancementContext:
    """
    AI Enhancement Context for LLM interactions.

    This model tracks AI enhancement requests across all 37 tools,
    maintaining context for intelligent assistance while preserving
    original algorithm fallback capabilities.
    """

    def __init__(
        self,
        user_id: UUID,
        session_id: UUID,
        tool_name: str,
        domain: str,
        enhancement_type: AIEnhancementType,
        context_data: Dict[str, Any],
        prompt_template: str,
        **kwargs
    ):
        # Primary identification
        self.id = kwargs.get('id', uuid4())

        # User and session context
        self.user_id = user_id
        self.session_id = session_id

        # Tool and domain context
        self.tool_name = tool_name
        self.domain = domain  # security, productivity, mtg, infrastructure

        # Enhancement details
        self.enhancement_type = enhancement_type
        self.context_data = context_data
        self.prompt_template = prompt_template

        # Processing status
        self.status = kwargs.get('status', AIContextStatus.PENDING)

        # Performance tracking
        self.started_at = kwargs.get('started_at')
        self.completed_at = kwargs.get('completed_at')
        self.processing_duration_ms = kwargs.get('processing_duration_ms')

        # Results
        self.enhancement_result = kwargs.get('enhancement_result')
        self.confidence_score = kwargs.get('confidence_score')
        self.fallback_used = kwargs.get('fallback_used', False)

        # Error handling
        self.error_message = kwargs.get('error_message')
        self.retry_count = kwargs.get('retry_count', 0)

        # Metadata
        now = datetime.now()
        self.created_at = kwargs.get('created_at', now)
        self.updated_at = kwargs.get('updated_at', now)

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary representation."""
        return {
            'id': str(self.id),
            'user_id': str(self.user_id),
            'session_id': str(self.session_id),
            'tool_name': self.tool_name,
            'domain': self.domain,
            'enhancement_type': self.enhancement_type.value,
            'context_data': self.context_data,
            'prompt_template': self.prompt_template,
            'status': self.status.value,
            'started_at': self.started_at.isoformat() if self.started_at else None,
            'completed_at': self.completed_at.isoformat() if self.completed_at else None,
            'processing_duration_ms': self.processing_duration_ms,
            'enhancement_result': self.enhancement_result,
            'confidence_score': self.confidence_score,
            'fallback_used': self.fallback_used,
            'error_message': self.error_message,
            'retry_count': self.retry_count,
            'created_at': self.created_at.isoformat(),
            'updated_at': self.updated_at.isoformat(),
        }


class AIEnhancementRequest:
    """Schema for requesting AI enhancement."""

    def __init__(
        self,
        tool_name: str,
        domain: str,
        enhancement_type: AIEnhancementType,
        context_data: Dict[str, Any],
        user_preferences: Optional[Dict[str, Any]] = None,
        timeout_ms: Optional[int] = None
    ):
        self.tool_name = tool_name
        self.domain = domain
        self.enhancement_type = enhancement_type
        self.context_data = context_data
        self.user_preferences = user_preferences or {}
        # Default 1 second for security domain performance requirement
        self.timeout_ms = timeout_ms or 1000


class AIEnhancementResponse:
    """Schema for AI enhancement response."""

    def __init__(
        self,
        context_id: UUID,
        status: AIContextStatus,
        processing_duration_ms: Optional[int] = None,
        enhancement_result: Optional[Dict[str, Any]] = None,
        confidence_score: Optional[float] = None,
        fallback_used: bool = False,
        error_message: Optional[str] = None,
        suggestions: Optional[List[str]] = None
    ):
        self.context_id = context_id
        self.status = status
        self.processing_duration_ms = processing_duration_ms
        self.enhancement_result = enhancement_result
        self.confidence_score = confidence_score
        self.fallback_used = fallback_used
        self.error_message = error_message
        self.suggestions = suggestions or []

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary representation."""
        return {
            'context_id': str(self.context_id),
            'status': self.status.value,
            'processing_duration_ms': self.processing_duration_ms,
            'enhancement_result': self.enhancement_result,
            'confidence_score': self.confidence_score,
            'fallback_used': self.fallback_used,
            'error_message': self.error_message,
            'suggestions': self.suggestions,
        }


