    # n8n integration
    n8n_workflow_id = Column(String(100))  # n8n workflow identifier
    n8n_definition = Column(JSON)  # n8n workflow definition
    auto_generated = Column(Boolean, default=False)
    pattern_based = Column(Boolean, default=False)

    # Tool orchestration
    involved_tools = Column(JSON, default=list)
    tool_sequence = Column(JSON, default=list)
    data_mappings = Column(JSON, default=dict)  # Tool-to-tool data mapping

    # Performance and monitoring
    execution_count = Column(Integer, default=0)
    success_count = Column(Integer, default=0)
    failure_count = Column(Integer, default=0)
    average_duration_ms = Column(Integer)
