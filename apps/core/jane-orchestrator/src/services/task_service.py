"""
TaskManagementService with AI Integration

This module provides comprehensive task management capabilities across all 37
integrated tools with AI-assisted executive function support. Handles task
creation, breakdown, scheduling, and cross-domain orchestration.

Constitutional Requirements:
- Executive function accommodations for ADHD/autism users
- Domain-specific performance targets (<1s Security, <2s Productivity, etc.)
- Cross-tool context awareness and coordination
- AI-assisted task breakdown and optimization
- Proactive reminder system with pattern recognition

Author: Generated by Phase 5 implementation
Created: 2025-10-28
"""

import logging
from datetime import datetime, timedelta
from typing import Any, Dict, List, Optional, Tuple

from sqlalchemy.orm import Session

from ..data.models.ai_context import (AIEnhancementRequest, AIEnhancementType,
                                      TaskBreakdownAIContext)
from ..data.models.task import (DOMAIN_PERFORMANCE_TARGETS,
                                EXECUTIVE_FUNCTION_TEMPLATES, Task,
                                TaskBreakdown, TaskComplexity,
                                TaskCreateRequest, TaskDomain, TaskReminder,
                                TaskStatus, TaskUpdateRequest, Workflow)
from ..data.models.user_profile import UserProfile

logger = logging.getLogger(__name__)


class TaskManagementService:
    """
    Core task management service with AI integration.

    Provides comprehensive task lifecycle management including:
    - AI-assisted task creation and breakdown
    - Executive function accommodations
    - Cross-domain task orchestration
    - Performance monitoring per constitutional requirements
    - Proactive reminder system
    """

    def __init__(self, db_session: Session, ai_service=None):
        """Initialize Task Management Service."""
        self.db = db_session
        self.ai_service = ai_service

        # Domain performance targets (constitutional compliance)
        self.performance_targets = DOMAIN_PERFORMANCE_TARGETS

        # Executive function templates
        self.templates = EXECUTIVE_FUNCTION_TEMPLATES

    async def create_task(
        self,
        user_id: str,
        request: TaskCreateRequest,
        user_profile: Optional[UserProfile] = None
    ) -> Tuple[Task, Optional[List[TaskBreakdown]]]:
        """
        Create a new task with optional AI breakdown.

        Args:
            user_id: User creating the task
            request: Task creation request
            user_profile: User profile for accommodations

        Returns:
            Tuple of (created_task, optional_breakdown_steps)
        """
        try:
            start_time = datetime.now()

            # Create base task
            task = Task(
                user_id=user_id,
                title=request.title,
                description=request.description,
                priority=request.priority.value,
                complexity=request.complexity.value,
                domain=request.domain.value,
                primary_tool=request.primary_tool,
                deadline=request.deadline,
                ai_breakdown_requested=request.ai_breakdown_requested,
                user_accommodations=request.user_accommodations,
                domain_performance_target_ms=self.performance_targets.get(
                    request.domain, 2000
                )
            )

            # Apply executive function accommodations
            if user_profile:
                task = self._apply_user_accommodations(task, user_profile)

            # Apply task template if applicable
            task = self._apply_task_template(task)

            self.db.add(task)
            self.db.flush()  # Ensure task ID is generated

            breakdown_steps = []

            # Request AI breakdown if needed
            if request.ai_breakdown_requested and self.ai_service:
                breakdown_steps = await self._generate_ai_breakdown(
                    task, user_profile
                )

            # Calculate performance metrics
            processing_time = (
                datetime.now() - start_time).total_seconds() * 1000
            target_time = self.performance_targets.get(request.domain, 2000)
            task.actual_performance_ms = int(processing_time)
            task.performance_met = processing_time <= target_time

            self.db.commit()

            logger.info(
                f"Created task {task.id} in {processing_time:.0f}ms "
                f"(target: {target_time}ms)"
            )

            return task, breakdown_steps

        except Exception as e:
            self.db.rollback()
            logger.error(f"Failed to create task: {e}")
            raise

    async def update_task(
        self,
        user_id: str,
        request: TaskUpdateRequest
    ) -> Task:
        """Update an existing task."""
        try:
            task = self.db.query(Task).filter(
                Task.id == request.task_id,
                Task.user_id == user_id
            ).first()

            if not task:
                raise ValueError(f"Task {request.task_id} not found")

            # Update fields
            if request.title:
                task.title = request.title
            if request.description:
                task.description = request.description
            if request.status:
                task.status = request.status.value
                if request.status == TaskStatus.IN_PROGRESS:
                    task.started_at = datetime.now()
                elif request.status == TaskStatus.COMPLETED:
                    task.completed_at = datetime.now()
                    task.progress_percentage = 100.0
            if request.priority:
                task.priority = request.priority.value
            if request.progress_percentage is not None:
                task.progress_percentage = request.progress_percentage

            task.updated_at = datetime.now()

            self.db.commit()
            return task

        except Exception as e:
            self.db.rollback()
            logger.error(f"Failed to update task {request.task_id}: {e}")
            raise

    async def get_user_tasks(
        self,
        user_id: str,
        status_filter: Optional[List[TaskStatus]] = None,
        domain_filter: Optional[List[TaskDomain]] = None,
        limit: int = 50,
        offset: int = 0
    ) -> List[Task]:
        """Get tasks for a user with optional filters."""
        query = self.db.query(Task).filter(Task.user_id == user_id)

        if status_filter:
            status_values = [s.value for s in status_filter]
            query = query.filter(Task.status.in_(status_values))

        if domain_filter:
            domain_values = [d.value for d in domain_filter]
            query = query.filter(Task.domain.in_(domain_values))

        return query.order_by(Task.created_at.desc()).offset(offset).limit(limit).all()

    async def get_task_breakdown(
        self,
        user_id: str,
        task_id: str
    ) -> List[TaskBreakdown]:
        """Get AI-generated breakdown for a task."""
        return self.db.query(TaskBreakdown).filter(
            TaskBreakdown.task_id == task_id,
            TaskBreakdown.user_id == user_id
        ).order_by(TaskBreakdown.step_number).all()

    async def update_breakdown_step(
        self,
        user_id: str,
        breakdown_id: str,
        completed: bool,
        actual_minutes: Optional[int] = None,
        difficulty_rating: Optional[int] = None,
        user_notes: Optional[str] = None
    ) -> TaskBreakdown:
        """Update a task breakdown step."""
        step = self.db.query(TaskBreakdown).filter(
            TaskBreakdown.id == breakdown_id,
            TaskBreakdown.user_id == user_id
        ).first()

        if not step:
            raise ValueError(f"Breakdown step {breakdown_id} not found")

        step.completed = completed
        if completed:
            step.completed_at = datetime.now()
        if actual_minutes:
            step.actual_minutes = actual_minutes
        if difficulty_rating:
            step.difficulty_rating = difficulty_rating
        if user_notes:
            step.user_notes = user_notes
            step.user_modified = True

        step.updated_at = datetime.now()

        # Update parent task progress
        await self._update_task_progress(step.task_id)

        self.db.commit()
        return step

    async def create_reminder(
        self,
        user_id: str,
        task_id: str,
        reminder_type: str,
        reminder_time: datetime,
        message: Optional[str] = None,
        context_data: Optional[Dict[str, Any]] = None
    ) -> TaskReminder:
        """Create a proactive reminder for a task."""
        reminder = TaskReminder(
            task_id=task_id,
            user_id=user_id,
            reminder_type=reminder_type,
            reminder_time=reminder_time,
            message=message,
            context_data=context_data or {}
        )

        self.db.add(reminder)
        self.db.commit()
        return reminder

    async def get_due_reminders(
        self,
        user_id: str,
        current_time: Optional[datetime] = None
    ) -> List[TaskReminder]:
        """Get reminders that are due for a user."""
        if not current_time:
            current_time = datetime.now()

        return self.db.query(TaskReminder).filter(
            TaskReminder.user_id == user_id,
            TaskReminder.reminder_time <= current_time,
            TaskReminder.delivered == False,
            TaskReminder.snoozed_until.is_(None) |
            (TaskReminder.snoozed_until <= current_time)
        ).all()

    async def analyze_task_patterns(
        self,
        user_id: str,
        days_back: int = 30
    ) -> Dict[str, Any]:
        """Analyze user task patterns for AI insights."""
        cutoff_date = datetime.now() - timedelta(days=days_back)

        tasks = self.db.query(Task).filter(
            Task.user_id == user_id,
            Task.created_at >= cutoff_date
        ).all()

        patterns = {
            'total_tasks': len(tasks),
            'completed_tasks': len([t for t in tasks if t.status == TaskStatus.COMPLETED.value]),
            'average_completion_time': 0,
            'most_used_tools': {},
            'domain_distribution': {},
            'complexity_trends': {},
            'focus_score_average': 0,
            'context_switches_average': 0
        }

        if tasks:
            # Calculate averages
            completed_tasks = [t for t in tasks if t.actual_duration_minutes]
            if completed_tasks:
                patterns['average_completion_time'] = sum(
                    t.actual_duration_minutes for t in completed_tasks
                ) / len(completed_tasks)

            focus_scores = [t.focus_score for t in tasks if t.focus_score]
            if focus_scores:
                patterns['focus_score_average'] = sum(
                    focus_scores) / len(focus_scores)

            patterns['context_switches_average'] = sum(
                t.context_switches for t in tasks
            ) / len(tasks)

            # Tool usage patterns
            for task in tasks:
                if task.primary_tool:
                    patterns['most_used_tools'][task.primary_tool] = \
                        patterns['most_used_tools'].get(
                            task.primary_tool, 0) + 1

            # Domain distribution
            for task in tasks:
                patterns['domain_distribution'][task.domain] = \
                    patterns['domain_distribution'].get(task.domain, 0) + 1

            # Complexity trends
            for task in tasks:
                patterns['complexity_trends'][task.complexity] = \
                    patterns['complexity_trends'].get(task.complexity, 0) + 1

        return patterns

    # Private helper methods

    def _apply_user_accommodations(
        self,
        task: Task,
        user_profile: UserProfile
    ) -> Task:
        """Apply user-specific executive function accommodations."""
        accommodations = {}

        # ADHD accommodations
        if user_profile.adhd_accommodations:
            adhd = user_profile.adhd_accommodations
            accommodations.update({
                'break_reminders': adhd.get('time_awareness', False),
                'progress_indicators': adhd.get('progress_indicators', False),
                'task_breakdown': adhd.get('task_breakdown', False),
                'focus_mode': adhd.get('focus_mode', False)
            })

        # Autism accommodations
        if user_profile.autism_accommodations:
            autism = user_profile.autism_accommodations
            accommodations.update({
                'predictable_patterns': autism.get('predictable_patterns', False),
                'detailed_descriptions': autism.get('detailed_descriptions', False),
                'routine_optimization': autism.get('routine_optimization', False)
            })

        task.user_accommodations = accommodations
        return task

    def _apply_task_template(self, task: Task) -> Task:
        """Apply executive function task templates."""
        template_key = None

        # Determine template based on complexity and user accommodations
        if task.complexity == TaskComplexity.EXTENSIVE.value:
            template_key = "complex_project"
        elif task.user_accommodations.get('focus_mode'):
            template_key = "focus_session"
        elif task.domain in [TaskDomain.PRODUCTIVITY.value, TaskDomain.MTG.value]:
            template_key = "routine_task"

        if template_key and template_key in self.templates:
            template = self.templates[template_key]

            if 'break_intervals' in template:
                task.break_intervals = template['break_intervals']
            if 'reminder_settings' in template:
                task.reminder_settings.update(template['reminder_settings'])
            if 'ai_breakdown_requested' in template:
                task.ai_breakdown_requested = template['ai_breakdown_requested']

        return task

    async def _generate_ai_breakdown(
        self,
        task: Task,
        user_profile: Optional[UserProfile] = None
    ) -> List[TaskBreakdown]:
        """Generate AI-powered task breakdown."""
        if not self.ai_service:
            return []

        try:
            # Create AI context for task breakdown
            context = TaskBreakdownAIContext(
                original_task_description=task.description or task.title,
                estimated_duration=task.estimated_duration_minutes,
                required_tools=[
                    task.primary_tool] if task.primary_tool else [],
                domain_context=task.domain,
                constraints=[]
            )

            # Request AI enhancement
            request = AIEnhancementRequest(
                tool_name="task_management",
                domain=task.domain,
                enhancement_type=AIEnhancementType.TASK_BREAKDOWN,
                context_data=context.__dict__,
                timeout_ms=self.performance_targets.get(
                    TaskDomain(task.domain), 2000)
            )

            response = await self.ai_service.enhance_request(request)

            if response.status.value == "completed" and response.enhancement_result:
                return self._create_breakdown_steps(task, response.enhancement_result)

        except Exception as e:
            logger.error(f"AI breakdown failed for task {task.id}: {e}")

        return []

    def _create_breakdown_steps(
        self,
        task: Task,
        ai_result: Dict[str, Any]
    ) -> List[TaskBreakdown]:
        """Create breakdown steps from AI response."""
        steps = []

        ai_steps = ai_result.get('steps', [])

        for i, step_data in enumerate(ai_steps, 1):
            step = TaskBreakdown(
                task_id=task.id,
                user_id=task.user_id,
                step_number=i,
                step_title=step_data.get('title', f'Step {i}'),
                step_description=step_data.get('description', ''),
                estimated_minutes=step_data.get('estimated_minutes', 15),
                required_tool=step_data.get('required_tool'),
                depends_on_steps=step_data.get('depends_on', []),
                can_run_parallel=step_data.get('can_run_parallel', False),
                ai_generated=True,
                ai_confidence=ai_result.get('confidence', 0.8)
            )

            self.db.add(step)
            steps.append(step)

        return steps

    async def _update_task_progress(self, task_id: str):
        """Update task progress based on completed breakdown steps."""
        task = self.db.query(Task).filter(Task.id == task_id).first()
        if not task:
            return

        breakdown_steps = self.db.query(TaskBreakdown).filter(
            TaskBreakdown.task_id == task_id
        ).all()

        if breakdown_steps:
            completed_steps = [s for s in breakdown_steps if s.completed]
            progress = (len(completed_steps) / len(breakdown_steps)) * 100
            task.progress_percentage = progress

            # Update task status based on progress
            if progress == 100:
                task.status = TaskStatus.COMPLETED.value
                task.completed_at = datetime.now()
            elif progress > 0 and task.status == TaskStatus.CREATED.value:
                task.status = TaskStatus.IN_PROGRESS.value
                task.started_at = datetime.now()


class WorkflowManagementService:
    """
    Workflow management service for n8n integration and adaptive workflows.

    Handles workflow creation, execution, and pattern-based optimization.
    """

    def __init__(self, db_session: Session, n8n_client=None):
        """Initialize Workflow Management Service."""
        self.db = db_session
        self.n8n_client = n8n_client

    async def create_workflow(
        self,
        user_id: str,
        name: str,
        description: str,
        domain: TaskDomain,
        involved_tools: List[str],
        workflow_definition: Optional[Dict[str, Any]] = None
    ) -> Workflow:
        """Create a new workflow."""
        workflow = Workflow(
            user_id=user_id,
            name=name,
            description=description,
            domain=domain.value,
            involved_tools=involved_tools,
            n8n_definition=workflow_definition
        )

        self.db.add(workflow)
        self.db.commit()
        return workflow

    async def execute_workflow(
        self,
        workflow_id: str,
        execution_data: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """Execute a workflow through n8n."""
        workflow = self.db.query(Workflow).filter(
            Workflow.id == workflow_id
        ).first()

        if not workflow:
            raise ValueError(f"Workflow {workflow_id} not found")

        if not self.n8n_client:
            raise RuntimeError("n8n client not configured")

        try:
            start_time = datetime.now()

            # Execute through n8n
            result = await self.n8n_client.execute_workflow(
                workflow.n8n_workflow_id,
                execution_data or {}
            )

            # Update execution metrics
            duration = (datetime.now() - start_time).total_seconds() * 1000
            workflow.execution_count += 1
            workflow.last_execution = datetime.now()

            if result.get('success'):
                workflow.success_count += 1
            else:
                workflow.failure_count += 1

            # Update average duration
            if workflow.average_duration_ms:
                workflow.average_duration_ms = int(
                    (workflow.average_duration_ms + duration) / 2
                )
            else:
                workflow.average_duration_ms = int(duration)

            self.db.commit()
            return result

        except Exception as e:
            workflow.failure_count += 1
            self.db.commit()
            logger.error(f"Workflow execution failed: {e}")
            raise
