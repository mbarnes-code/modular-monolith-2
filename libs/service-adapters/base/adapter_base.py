"""
Base Service Adapter

This module provides the base class for all service adapters in the
modular monolith architecture. It defines the common interface and
functionality for integrating the 37 executive function tools.

Author: Generated by implementation phase
Created: 2025-10-28
"""

import logging
from abc import ABC, abstractmethod
from datetime import datetime
from typing import Any, Dict

logger = logging.getLogger(__name__)


class BaseServiceAdapter(ABC):
    """
    Base class for all service adapters.

    This class provides common functionality and interface for integrating
    all 37 tools while preserving their business logic and ensuring
    constitutional compliance.
    """

    def __init__(self, service_name: str, config: Dict[str, Any]):
        """Initialize base adapter."""
        self.service_name = service_name
        self.config = config
        self.is_healthy = False
        self.last_health_check = None

        logger.info(f"Initializing {service_name} adapter")

    @abstractmethod
    async def initialize(self) -> None:
        """Initialize the service adapter."""
        pass

    @abstractmethod
    async def get_health_status(self) -> Dict[str, Any]:
        """Get service health status."""
        pass

    async def health_check(self) -> bool:
        """Perform health check and update status."""
        try:
            status = await self.get_health_status()
            self.is_healthy = status.get('healthy', False)
            self.last_health_check = datetime.now()
            return self.is_healthy
        except Exception as e:
            logger.error(f"{self.service_name} health check failed: {e}")
            self.is_healthy = False
            return False

    def get_service_info(self) -> Dict[str, Any]:
        """Get basic service information."""
        return {
            'service_name': self.service_name,
            'is_healthy': self.is_healthy,
            'last_health_check': (
                self.last_health_check.isoformat()
                if self.last_health_check else None
            ),
            'config_keys': list(self.config.keys())
        }
