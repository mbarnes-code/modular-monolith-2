    async def sync_offline_data(self) -> Dict[str, Any]:
        """
        Synchronize offline data when network becomes available.

        Returns:
            Synchronization results and statistics
        """
        if not self.offline_mode:
            return {'message': 'Not in offline mode', 'synced': 0}

        try:
            sync_stats = {
                'cases_synced': 0,
                'pcap_jobs_synced': 0,
                'errors': []
            }

            # Sync pending cases
            pending_cases = {
                k: v for k, v in self._local_cache.get('cases', {}).items()
                if v.get('sync_pending', False)
            }

            for case_id, case_data in pending_cases.items():
                try:
                    # Remove offline metadata before syncing
                    clean_case_data = {
                        k: v for k, v in case_data.items()
                        if k not in ['offline_created', 'sync_pending']
                    }

                    await self._create_case_online(clean_case_data)

                    # Mark as synced
                    self._local_cache['cases'][case_id]['sync_pending'] = False
                    sync_stats['cases_synced'] += 1

                except Exception as e:
                    sync_stats['errors'].append(
                        f"Failed to sync case {case_id}: {e}"
                    )

            # Sync pending PCAP jobs
            pending_pcap = {
                k: v for k, v in self._local_cache.get('pcap_jobs', {}).items()
                if v.get('sync_pending', False)
            }

            for job_id, job_data in pending_pcap.items():
                try:
                    await self._request_pcap_online(
                        job_data['filter_criteria'],
                        job_data['time_range']
                    )

                    # Mark as synced
                    self._local_cache['pcap_jobs'][job_id]['sync_pending'] = False
                    sync_stats['pcap_jobs_synced'] += 1

                except Exception as e:
                    sync_stats['errors'].append(
                        f"Failed to sync PCAP job {job_id}: {e}"
                    )

            logger.info(
                f"SecurityOnion sync completed: {sync_stats['cases_synced']} cases, "
                f"{sync_stats['pcap_jobs_synced']} PCAP jobs synced"
            )

            return sync_stats

        except Exception as e:
            logger.error(f"SecurityOnion sync failed: {e}")
            raise ServiceError(f"Data synchronization failed: {e}")

