class MISPAdapter(BaseServiceAdapter):
    """
    MISP service adapter for threat intelligence integration.

    This adapter provides a unified interface to MISP functionality while
    preserving the original business logic and threat intelligence correlation
    algorithms. Supports both online and airgapped operation modes.

    Implements T1875 requirements:
    - Resolves all technology stack dependencies (PyMISP, Redis, etc.)
    - Handles external integrations (STIX, CVE, etc.)
    - Maintains 100% API compatibility
    """

    def __init__(self, config: Dict[str, Any]):
        """Initialize MISP adapter with configuration."""
        super().__init__(service_name="MISP", config=config)

        # MISP-specific configuration
        self.misp_url = config.get('misp_url', 'http://localhost:8080')
        self.api_key = config.get('api_key')
        self.verify_ssl = config.get('verify_ssl', True)
        self.timeout = config.get('timeout', 30)

        # Airgapped mode settings
        self.offline_mode = config.get('offline_mode', False)
        self.local_data_path = Path(
            config.get('local_data_path', '/tmp/misp_cache')
        )

        # Performance settings (constitutional requirement: <1s for security)
        self.max_response_time_ms = config.get('max_response_time_ms', 1000)

        # Redis configuration for caching and session management
        self.redis_host = config.get('redis_host', '127.0.0.1')
        self.redis_port = config.get('redis_port', 6379)
        self.redis_db = config.get('redis_database', 13)
        self.redis_password = config.get('redis_password', '')

        # External integration settings
        self.stix_enabled = config.get('stix_enabled', True)
        self.cve_lookup_enabled = config.get('cve_lookup_enabled', True)
        self.cve_url = config.get(
            'cveurl', 'https://vulnerability.circl.lu/vuln/')

        # Initialize connections
        self._misp_client = None
        self._redis_client = None
        self._local_cache = {}
        self._correlation_cache = {}

        # PyMISP availability check
        if not PYMISP_AVAILABLE and not self.offline_mode:
            logger.warning(
                "PyMISP not available, forcing offline mode"
            )
            self.offline_mode = True

        logger.info(
            f"MISP adapter initialized: offline_mode={self.offline_mode}, "
            f"stix_enabled={self.stix_enabled}"
        )

    async def initialize(self) -> None:
        """Initialize MISP connection and verify availability."""
        try:
            # Initialize Redis connection
            await self._connect_to_redis()

            # Initialize MISP client if not in offline mode
            if not self.offline_mode and self.api_key and PYMISP_AVAILABLE:
                await self._connect_to_misp()

            # Load local cache and correlation data
            await self._load_local_cache()
            await self._initialize_correlation_engine()

            # Verify external integrations
            await self._verify_external_integrations()

            self.is_healthy = True
            logger.info("MISP adapter initialization completed successfully")

        except Exception as e:
            logger.error(f"MISP initialization failed: {e}")
            self.is_healthy = False
            raise ServiceError(f"MISP initialization failed: {e}")

    async def _connect_to_redis(self) -> None:
        """Initialize Redis connection for caching and sessions."""
        try:
            if redis:
                self._redis_client = redis.Redis(
                    host=self.redis_host,
                    port=self.redis_port,
                    db=self.redis_db,
                    password=self.redis_password if self.redis_password else None,
                    decode_responses=True,
                    socket_timeout=5
                )
                # Test connection
                await asyncio.get_event_loop().run_in_executor(
                    None, self._redis_client.ping
                )
                logger.info("Redis connection established")
            else:
                logger.warning("Redis not available, using memory cache")
        except Exception as e:
            logger.warning(f"Redis connection failed: {e}, using memory cache")
            self._redis_client = None

    async def _connect_to_misp(self) -> None:
        """Connect to MISP instance using PyMISP."""
        try:
            if PYMISP_AVAILABLE:
                # Initialize PyMISP client with proper error handling
                loop = asyncio.get_event_loop()
                self._misp_client = await loop.run_in_executor(
                    None,
                    lambda: PyMISP(
                        self.misp_url,
                        self.api_key,
                        self.verify_ssl,
                        timeout=(self.timeout, self.timeout)
                    )
                )

                # Test connection by getting MISP version
                version_info = await loop.run_in_executor(
                    None, self._misp_client.get_version
                )

                logger.info(
                    f"Connected to MISP {version_info.get('version', 'unknown')} "
                    f"at {self.misp_url}"
                )
            else:
                raise ServiceError("PyMISP not available")

        except Exception as e:
            logger.error(f"MISP connection failed: {e}")
            raise ServiceError(f"Failed to connect to MISP: {e}")

    async def _load_local_cache(self) -> None:
        """Load local cache for offline operations."""
        try:
            # Ensure cache directory exists
            self.local_data_path.mkdir(parents=True, exist_ok=True)

            # Initialize cache structure
            self._local_cache = {
                'events': {},
                'attributes': {},
                'objects': {},
                'taxonomies': {},
                'galaxies': {},
                'correlations': {},
                'feed_data': {}
            }

            # Load from persistent storage if available
            cache_file = self.local_data_path / 'misp_cache.json'
            if cache_file.exists():
                with open(cache_file, 'r') as f:
                    cached_data = json.load(f)
                    self._local_cache.update(cached_data)
                    logger.info(
                        f"Loaded {len(cached_data.get('events', {}))} "
                        f"events from local cache"
                    )

            logger.info("MISP local cache initialized")
        except Exception as e:
            logger.warning(f"Failed to load MISP cache: {e}")

    async def _initialize_correlation_engine(self) -> None:
        """Initialize the threat intelligence correlation engine."""
        try:
            # Load correlation rules and patterns
            self._correlation_cache = {
                'rules': await self._load_correlation_rules(),
                'thresholds': {
                    'ssdeep_threshold': 40,  # From MISP config
                    'fuzzy_threshold': 0.7,
                    'temporal_threshold': 86400 * 7  # 7 days
                },
                'patterns': await self._load_pattern_database()
            }

            logger.info("Correlation engine initialized")
        except Exception as e:
            logger.warning(f"Correlation engine initialization failed: {e}")

