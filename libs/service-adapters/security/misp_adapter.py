        integrations_status = {}

        # Test CVE lookup service
        if self.cve_lookup_enabled:
            try:
                async with asyncio.timeout(5):
                    response = await asyncio.get_event_loop().run_in_executor(
                        None,
                        lambda: requests.get(
                            f"{self.cve_url}CVE-2021-44228",
                            timeout=5
                        )
                    )
                    integrations_status['cve_lookup'] = response.status_code == 200
            except Exception as e:
                integrations_status['cve_lookup'] = False
                logger.warning(f"CVE lookup service not available: {e}")

