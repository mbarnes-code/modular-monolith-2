    async def _create_event_online(
        self,
        event_data: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Create event using online MISP API with PyMISP."""
        if not self._misp_client or not PYMISP_AVAILABLE:
            raise ServiceError("MISP client not available")

        try:
            loop = asyncio.get_event_loop()

            # Create MISPEvent object
            misp_event = await loop.run_in_executor(
                None, lambda: MISPEvent()
            )

            # Set event properties
            misp_event.info = event_data['info']
            misp_event.threat_level_id = event_data['threat_level_id']
            misp_event.analysis = event_data.get('analysis', 0)
            misp_event.distribution = event_data.get('distribution', 1)

            # Add event to MISP
            result = await loop.run_in_executor(
                None, self._misp_client.add_event, misp_event
            )

            # Process result
            if hasattr(result, 'get') and 'Event' in result:
                event_info = result['Event']
            else:
                event_info = result

            return {
                'id': event_info.get('id'),
                'uuid': event_info.get('uuid'),
                'info': event_info.get('info'),
                'threat_level_id': event_info.get('threat_level_id'),
                'published': event_info.get('published', False),
                'timestamp': event_info.get('timestamp'),
                'created': True
            }

        except PyMISPError as e:
            logger.error(f"PyMISP event creation error: {e}")
            raise ServiceError(f"Event creation failed: {e}")
        except Exception as e:
            logger.error(f"Event creation error: {e}")
            raise ServiceError(f"Failed to create event: {e}")

