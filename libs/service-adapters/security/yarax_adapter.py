"""
YARA-X Service Adapter

This module provides the service adapter for YARA-X integration.
It preserves business logic while providing unified interface for the
security domain within the modular monolith architecture.

YARA-X is a pattern matching tool designed for malware researchers,
providing advanced malware detection and classification capabilities.

Author: Generated by implementation phase
Created: 2025-10-28
"""

import logging
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, Optional

from ...shared.exceptions import ServiceError, ValidationError
from ..base.adapter_base import BaseServiceAdapter

logger = logging.getLogger(__name__)


class YARAXAdapter(BaseServiceAdapter):
    """
    YARA-X service adapter for malware pattern matching.

    This adapter provides a unified interface to YARA-X functionality while
    preserving the original business logic for malware detection, pattern
    matching, and threat classification. Supports both online and airgapped
    operation modes.
    """

    def __init__(self, config: Dict[str, Any]):
        """Initialize YARA-X adapter with configuration."""
        super().__init__(service_name="YARA-X", config=config)

        # YARA-X specific configuration
        self.rules_directory = Path(config.get(
            'rules_directory', '/opt/yara_rules'
        ))
        self.custom_rules_path = Path(config.get(
            'custom_rules_path', '/opt/custom_yara_rules'
        ))
        self.timeout = config.get('timeout', 30)

        # Performance settings (constitutional requirement: <1s for security)
        self.max_response_time_ms = config.get('max_response_time_ms', 1000)
        self.max_file_size_mb = config.get('max_file_size_mb', 100)

        # YARA-X compilation settings
        self.relaxed_re_syntax = config.get('relaxed_re_syntax', False)
        self.colorize_errors = config.get('colorize_errors', True)

        # Airgapped mode settings
        self.offline_mode = config.get('offline_mode', False)
        self.local_cache = {}

        # Initialize YARA components
        self._yara_compiler = None
        self._compiled_rules = None
        self._rule_namespaces = {}

        logger.info(
            f"YARA-X adapter initialized: offline_mode={self.offline_mode}"
        )

    async def initialize(self) -> None:
        """Initialize YARA-X connection and load rules."""
        try:
            # Import YARA-X library
            await self._import_yara_x()

            # Load and compile rules
            await self._load_rule_files()
            await self._compile_rules()

            self.is_healthy = True

        except Exception as e:
            logger.error(f"YARA-X initialization failed: {e}")
            self.is_healthy = False
            raise ServiceError(f"YARA-X initialization failed: {e}")

    async def _import_yara_x(self) -> None:
        """Import YARA-X library with error handling."""
        try:
            global yara_x
            import yara_x
            logger.info("YARA-X library imported successfully")
        except ImportError as e:
            logger.error(f"Failed to import YARA-X library: {e}")
            raise ServiceError(
                "YARA-X library not available. "
                "Install with: pip install yara-x"
            )

    async def _load_rule_files(self) -> None:
        """Load YARA rule files from configured directories."""
        try:
            self._rule_files = []

            # Load from main rules directory
            if self.rules_directory.exists():
                rule_files = list(self.rules_directory.glob("**/*.yar"))
                rule_files.extend(list(self.rules_directory.glob("**/*.yara")))
                self._rule_files.extend(rule_files)

            # Load from custom rules directory
            if self.custom_rules_path.exists():
                custom_files = list(self.custom_rules_path.glob("**/*.yar"))
                custom_files.extend(
                    list(self.custom_rules_path.glob("**/*.yara"))
                )
                self._rule_files.extend(custom_files)

            logger.info(f"Found {len(self._rule_files)} YARA rule files")

        except Exception as e:
            logger.warning(f"Failed to load some rule files: {e}")
            self._rule_files = []

    async def _compile_rules(self) -> None:
        """Compile YARA rules for scanning."""
        try:
            if not self._rule_files:
                logger.warning("No YARA rule files found to compile")
                return

            # Compile rules from files
            combined_rules = ""
            for rule_file in self._rule_files:
                try:
                    with open(rule_file, 'r', encoding='utf-8') as f:
                        rule_content = f.read()
                        combined_rules += f"\n// Rules from {rule_file}\n"
                        combined_rules += rule_content + "\n"
                except Exception as e:
                    logger.warning(
                        f"Failed to read rule file {rule_file}: {e}")

            if combined_rules:
                self._compiled_rules = yara_x.compile(combined_rules)
                logger.info("YARA rules compiled successfully")
            else:
                logger.warning("No valid YARA rules to compile")

        except Exception as e:
            logger.error(f"YARA rule compilation failed: {e}")
            # Continue without compiled rules for graceful degradation
            self._compiled_rules = None

    async def scan_file(
        self,
        file_path: str,
        rule_namespace: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Scan file with YARA-X rules.

        Args:
            file_path: Path to file to scan
            rule_namespace: Optional rule namespace filter

        Returns:
            Dictionary containing scan results and metadata
        """
        start_time = datetime.now()

        try:
            # Validate file path
            await self._validate_file_path(file_path)

            if not self._compiled_rules:
                raise ServiceError("No compiled YARA rules available")

            # Perform scan
            results = await self._scan_file_with_rules(
                file_path, rule_namespace
            )

            # Calculate processing time
            processing_time = (
                datetime.now() - start_time
            ).total_seconds() * 1000

            # Ensure constitutional compliance (<1s for security domain)
            if processing_time > self.max_response_time_ms:
                logger.warning(
                    f"YARA-X scan exceeded time limit: {processing_time}ms"
                )

            return {
                'file_path': file_path,
                'scan_results': results,
                'metadata': {
                    'rules_matched': len(results.get('matches', [])),
                    'processing_time_ms': processing_time,
                    'rule_namespace': rule_namespace,
                    'timestamp': datetime.now().isoformat()
                }
            }

        except Exception as e:
            logger.error(f"YARA-X file scan failed: {e}")
            raise ServiceError(f"File scan failed: {e}")

    async def _validate_file_path(self, file_path: str) -> None:
        """Validate file path and size."""
        path = Path(file_path)

        if not path.exists():
            raise ValidationError(f"File not found: {file_path}")

        if not path.is_file():
            raise ValidationError(f"Path is not a file: {file_path}")

        # Check file size
        file_size_mb = path.stat().st_size / (1024 * 1024)
        if file_size_mb > self.max_file_size_mb:
            raise ValidationError(
                f"File too large: {file_size_mb:.1f}MB "
                f"(max: {self.max_file_size_mb}MB)"
            )

    async def _scan_file_with_rules(
        self,
        file_path: str,
        rule_namespace: Optional[str]
    ) -> Dict[str, Any]:
        """Scan file with compiled YARA rules."""
        try:
            # Read file for scanning
            with open(file_path, 'rb') as f:
                file_data = f.read()

            # Perform YARA scan
            scan_results = self._compiled_rules.scan(file_data)

            # Process results
            matches = []
            for rule in scan_results.matching_rules:
                # Filter by namespace if specified
                if rule_namespace and rule_namespace != rule.namespace:
                    continue

                rule_match = {
                    'rule_name': rule.identifier,
                    'namespace': getattr(rule, 'namespace', 'default'),
                    'tags': list(rule.tags) if hasattr(rule, 'tags') else [],
                    'metadata': dict(rule.metadata) if hasattr(
                        rule, 'metadata'
                    ) else {},
                    'patterns': []
                }

                # Extract pattern matches
                for pattern in rule.patterns:
                    pattern_info = {
                        'identifier': pattern.identifier,
                        'matches': []
                    }

                    for match in pattern.matches:
                        pattern_info['matches'].append({
                            'offset': match.offset,
                            'length': match.length,
                            'matched_data': match.matched_data if hasattr(
                                match, 'matched_data'
                            ) else None
                        })

                    rule_match['patterns'].append(pattern_info)

                matches.append(rule_match)

            return {
                'matches': matches,
                'total_matches': len(matches),
                'file_size': len(file_data)
            }

        except Exception as e:
            logger.error(f"YARA scan execution failed: {e}")
            raise ServiceError(f"YARA scan execution failed: {e}")

    async def scan_data(
        self,
        data: bytes,
        rule_namespace: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Scan binary data with YARA-X rules.

        Args:
            data: Binary data to scan
            rule_namespace: Optional rule namespace filter

        Returns:
            Dictionary containing scan results and metadata
        """
        start_time = datetime.now()

        try:
            # Validate data
            await self._validate_scan_data(data)

            if not self._compiled_rules:
                raise ServiceError("No compiled YARA rules available")

            # Perform scan
            scan_results = self._compiled_rules.scan(data)

            # Process results (similar to file scan)
            matches = []
            for rule in scan_results.matching_rules:
                if rule_namespace and rule_namespace != rule.namespace:
                    continue

                rule_match = {
                    'rule_name': rule.identifier,
                    'namespace': getattr(rule, 'namespace', 'default'),
                    'tags': list(rule.tags) if hasattr(rule, 'tags') else [],
                    'metadata': dict(rule.metadata) if hasattr(
                        rule, 'metadata'
                    ) else {},
                    'patterns': []
                }

                for pattern in rule.patterns:
                    pattern_info = {
                        'identifier': pattern.identifier,
                        'matches': []
                    }

                    for match in pattern.matches:
                        pattern_info['matches'].append({
                            'offset': match.offset,
                            'length': match.length
                        })

                    rule_match['patterns'].append(pattern_info)

                matches.append(rule_match)

            # Calculate processing time
            processing_time = (
                datetime.now() - start_time
            ).total_seconds() * 1000

            return {
                'scan_results': {
                    'matches': matches,
                    'total_matches': len(matches),
                    'data_size': len(data)
                },
                'metadata': {
                    'processing_time_ms': processing_time,
                    'rule_namespace': rule_namespace,
                    'timestamp': datetime.now().isoformat()
                }
            }

        except Exception as e:
            logger.error(f"YARA-X data scan failed: {e}")
            raise ServiceError(f"Data scan failed: {e}")

    async def _validate_scan_data(self, data: bytes) -> None:
        """Validate binary data for scanning."""
        if not isinstance(data, bytes):
            raise ValidationError("Data must be bytes")

        # Check data size
        data_size_mb = len(data) / (1024 * 1024)
        if data_size_mb > self.max_file_size_mb:
            raise ValidationError(
                f"Data too large: {data_size_mb:.1f}MB "
                f"(max: {self.max_file_size_mb}MB)"
            )

    async def compile_custom_rule(
        self,
        rule_content: str,
        rule_name: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Compile custom YARA rule for immediate use.

        Args:
            rule_content: YARA rule content
            rule_name: Optional name for the rule

        Returns:
            Compilation results and rule information
        """
        try:
            # Validate rule content
            await self._validate_rule_content(rule_content)

            # Compile rule
            compiled_rule = yara_x.compile(rule_content)

            # Store compiled rule for later use
            rule_id = rule_name or f"custom_rule_{datetime.now().timestamp()}"
            self._rule_namespaces[rule_id] = compiled_rule

            logger.info(f"Custom YARA rule compiled: {rule_id}")

            return {
                'rule_id': rule_id,
                'rule_content': rule_content,
                'compiled': True,
                'timestamp': datetime.now().isoformat()
            }

        except Exception as e:
            logger.error(f"Custom rule compilation failed: {e}")
            raise ServiceError(f"Rule compilation failed: {e}")

    async def _validate_rule_content(self, rule_content: str) -> None:
        """Validate YARA rule content."""
        if not rule_content or not rule_content.strip():
            raise ValidationError("Rule content cannot be empty")

        # Basic syntax validation
        if 'rule ' not in rule_content:
            raise ValidationError("Rule content must contain 'rule' keyword")

        if 'condition:' not in rule_content:
            raise ValidationError(
                "Rule content must contain 'condition:' section")

    async def get_rule_info(self) -> Dict[str, Any]:
        """
        Get information about loaded YARA rules.

        Returns:
            Rule statistics and information
        """
        try:
            rule_info = {
                'total_rule_files': len(self._rule_files),
                'rules_compiled': bool(self._compiled_rules),
                'custom_rules': len(self._rule_namespaces),
                'rule_directories': [
                    str(self.rules_directory),
                    str(self.custom_rules_path)
                ],
                'timestamp': datetime.now().isoformat()
            }

            # Add file-level statistics
            if self._rule_files:
                rule_info['rule_files'] = [
                    {
                        'path': str(rule_file),
                        'size': rule_file.stat().st_size,
                        'modified': datetime.fromtimestamp(
                            rule_file.stat().st_mtime
                        ).isoformat()
                    }
                    for rule_file in self._rule_files
                ]

            return rule_info

        except Exception as e:
            logger.error(f"Failed to get rule info: {e}")
            raise ServiceError(f"Failed to get rule information: {e}")

    async def reload_rules(self) -> Dict[str, Any]:
        """
        Reload YARA rules from directories.

        Returns:
            Reload results and statistics
        """
        try:
            logger.info("Reloading YARA rules")

            # Clear existing rules
            self._compiled_rules = None
            self._rule_files = []

            # Reload and compile rules
            await self._load_rule_files()
            await self._compile_rules()

            result = {
                'reloaded': True,
                'total_rule_files': len(self._rule_files),
                'rules_compiled': bool(self._compiled_rules),
                'timestamp': datetime.now().isoformat()
            }

            logger.info(
                f"YARA rules reloaded: {result['total_rule_files']} files")
            return result

        except Exception as e:
            logger.error(f"Rule reload failed: {e}")
            raise ServiceError(f"Rule reload failed: {e}")

    async def get_health_status(self) -> Dict[str, Any]:
        """Get YARA-X service health status."""
        try:
            status = {
                'service': 'YARA-X',
                'healthy': self.is_healthy,
                'offline_mode': self.offline_mode,
                'timestamp': datetime.now().isoformat()
            }

            # Check YARA-X library availability
            try:
                import yara_x
                status['yara_x_available'] = True
                status['yara_x_version'] = getattr(
                    yara_x, '__version__', 'unknown'
                )
            except ImportError:
                status['yara_x_available'] = False

            # Check rule compilation status
            status['rules_status'] = {
                'total_rule_files': len(self._rule_files),
                'rules_compiled': bool(self._compiled_rules),
                'custom_rules': len(self._rule_namespaces),
                'rules_directory_exists': self.rules_directory.exists(),
                'custom_rules_directory_exists': self.custom_rules_path.exists()
            }

            return status

        except Exception as e:
            logger.error(f"YARA-X health check failed: {e}")
            return {
                'service': 'YARA-X',
                'healthy': False,
                'error': str(e),
                'timestamp': datetime.now().isoformat()
            }
